import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import {
	existsSync,
	mkdirSync,
	mkdtempSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import test from "node:test";

import {
	pathPackageNames,
	repositoryEnvironment,
	staleStandaloneLockfiles,
	trackedLockfiles,
} from "../refresh-release-lockfiles.ts";

const ROOT_LOCKFILE = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "pina"
version = "0.22.0"
dependencies = [
 "pina_macros",
 "pinocchio",
]

[[package]]
name = "pina_macros"
version = "0.22.0"

[[package]]
name = "pinocchio"
version = "0.11.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abc"
`;

const PINA_FIXTURE_LOCKFILE = `version = 4

[[package]]
name = "counter_pina"
version = "0.0.0"
dependencies = [
 "pina",
]

[[package]]
name = "pina"
version = "0.22.0"
`;

const FOREIGN_FIXTURE_LOCKFILE = `version = 4

[[package]]
name = "counter_anchor"
version = "0.0.0"

[[package]]
name = "anchor-lang"
version = "2.0.0"
source = "git+https://github.com/example/anchor#0123abc"
`;

/**
 * Create a scratch repository holding `files` and stage the `tracked` ones.
 *
 * Staging is enough for `git ls-files`, so the fixture needs no commit. The
 * commands run without the repository a git hook may have exported and without
 * global or system configuration, so they can only ever touch `root`.
 */
function createRepository(
	files: ReadonlyMap<string, string>,
	tracked: readonly string[],
): string {
	const root = mkdtempSync(join(tmpdir(), "pina-release-lockfiles-"));
	for (const [path, contents] of files) {
		mkdirSync(dirname(join(root, path)), { recursive: true });
		writeFileSync(join(root, path), contents);
	}

	const env = {
		...repositoryEnvironment(),
		GIT_CONFIG_GLOBAL: "/dev/null",
		GIT_CONFIG_NOSYSTEM: "1",
	};
	for (const args of [["init", "--quiet"], ["add", "--", ...tracked]]) {
		const result = spawnSync("git", args, { cwd: root, encoding: "utf8", env });
		assert.equal(result.status, 0, result.stderr);
	}

	return root;
}

test("reads only the packages a lockfile builds from local source", () => {
	assert.deepEqual(
		[...pathPackageNames(ROOT_LOCKFILE)],
		["pina", "pina_macros"],
	);
	assert.deepEqual([...pathPackageNames("version = 4\n")], []);
});

test("selects every standalone lockfile that records a workspace crate", () => {
	const lockfiles = new Map([
		["crates/pina_fuzz/Cargo.lock", PINA_FIXTURE_LOCKFILE],
		["Cargo.lock", ROOT_LOCKFILE],
		["benchmarks/counter/anchor/Cargo.lock", FOREIGN_FIXTURE_LOCKFILE],
		["benchmarks/counter/pina/Cargo.lock", PINA_FIXTURE_LOCKFILE],
	]);

	assert.deepEqual(staleStandaloneLockfiles(lockfiles), [
		"benchmarks/counter/pina/Cargo.lock",
		"crates/pina_fuzz/Cargo.lock",
	]);
});

test("refuses to guess the workspace crates without the root lockfile", () => {
	assert.throws(
		() =>
			staleStandaloneLockfiles(
				new Map([["nested/Cargo.lock", PINA_FIXTURE_LOCKFILE]]),
			),
		/Cargo\.lock is not tracked at the repository root/,
	);
});

test("reads tracked lockfiles and ignores untracked build output", () => {
	const root = createRepository(
		new Map([
			["Cargo.lock", ROOT_LOCKFILE],
			["benchmarks/counter/pina/Cargo.lock", PINA_FIXTURE_LOCKFILE],
			["target/walkthrough/Cargo.lock", PINA_FIXTURE_LOCKFILE],
			["benchmarks/counter/pina/NotCargo.lock", PINA_FIXTURE_LOCKFILE],
		]),
		[
			"Cargo.lock",
			"benchmarks/counter/pina/Cargo.lock",
			"benchmarks/counter/pina/NotCargo.lock",
		],
	);
	try {
		const tracked = trackedLockfiles(root);

		assert.deepEqual([...tracked.keys()].sort(), [
			"Cargo.lock",
			"benchmarks/counter/pina/Cargo.lock",
		]);
		assert.deepEqual(staleStandaloneLockfiles(tracked), [
			"benchmarks/counter/pina/Cargo.lock",
		]);
	} finally {
		rmSync(root, { force: true, recursive: true });
	}
});

test("drops the repository a git hook exports and keeps everything else", () => {
	assert.deepEqual(
		repositoryEnvironment({
			GIT_DIR: "/hook/repository/.git",
			GIT_INDEX_FILE: "/hook/repository/.git/index",
			GIT_WORK_TREE: "/hook/repository",
			HOME: "/home/pina",
			PATH: process.env.PATH,
		}),
		{ HOME: "/home/pina", PATH: process.env.PATH },
	);
});

test("reads the repository at the given root beneath a git hook", () => {
	// A hook's `GIT_DIR` outranks the working directory. Inherited unchanged, it
	// would make the fixture's `git init` rewrite the hook's repository and
	// point `git ls-files` at it.
	const hookRepository = mkdtempSync(join(tmpdir(), "pina-hook-repository-"));
	const hookGitDirectory = join(hookRepository, "hook.git");
	const previous = process.env.GIT_DIR;
	process.env.GIT_DIR = hookGitDirectory;

	let root: string | undefined;
	try {
		root = createRepository(new Map([["Cargo.lock", ROOT_LOCKFILE]]), [
			"Cargo.lock",
		]);

		assert.deepEqual([...trackedLockfiles(root).keys()], ["Cargo.lock"]);
		assert.equal(existsSync(hookGitDirectory), false);
	} finally {
		if (previous === undefined) {
			delete process.env.GIT_DIR;
		} else {
			process.env.GIT_DIR = previous;
		}
		rmSync(hookRepository, { force: true, recursive: true });
		if (root !== undefined) {
			rmSync(root, { force: true, recursive: true });
		}
	}
});

test("fails loudly when the tracked lockfiles cannot be listed", () => {
	const root = mkdtempSync(join(tmpdir(), "pina-release-lockfiles-"));
	rmSync(root, { force: true, recursive: true });

	assert.throws(() => trackedLockfiles(root), /git ls-files failed/);
});

test("fails loudly when git cannot name its repository variables", () => {
	assert.throws(
		() => repositoryEnvironment({ PATH: "" }),
		/git rev-parse --local-env-vars failed/,
	);
});
