//! Rust source emission for generated clap CLI crates.
#![allow(clippy::format_push_string)] // string assembly for templates
//! Templates use `@@TOKEN@@` placeholders replaced with [`tpl`] so braces in
//! the emitted Rust never collide with `format!` interpolation.

use std::collections::BTreeMap;

use crate::error::RenderError;
use crate::error::Result;
use crate::model::ArgKind;
use crate::model::CliModel;
use crate::model::FieldKind;
use crate::model::InstructionModel;
use crate::model::Resolution;
use crate::model::SeedModel;

pub(crate) const GENERATED_HEADER: &str = r"//! This code was AUTOGENERATED by `pina_cli_renderer`.
//! Please DO NOT EDIT THIS FILE directly.
//! Regenerate it from the program IDL instead.
#![allow(
	dead_code,
	clippy::doc_lazy_continuation,
	clippy::empty_line_after_doc_comments,
	clippy::too_many_arguments
)]
";

fn tpl(template: &str, replacements: &[(&str, String)]) -> String {
	let mut output = template.to_string();
	for (token, value) in replacements {
		output = output.replace(token, value);
	}
	output
}

/// Render every generated source file, keyed by path relative to the crate root.
///
/// # Errors
///
/// Returns an error when the model cannot be expressed as a CLI crate.
pub(crate) fn render_files(
	model: &CliModel,
	client_package: &str,
) -> Result<BTreeMap<String, String>> {
	if !model.has_commands() {
		return Err(RenderError::UnsupportedIdl {
			context: model.program_snake.clone(),
			reason: "the program declares no instructions and no accounts".to_string(),
		});
	}

	let client_crate = client_package.replace('-', "_");
	let mut files = BTreeMap::new();
	files.insert("src/main.rs".to_string(), emit_main(model));
	files.insert("src/context.rs".to_string(), emit_context(model));
	files.insert("src/commands/mod.rs".to_string(), emit_commands_mod(model));

	for instruction in &model.instructions {
		files.insert(
			format!("src/commands/{}.rs", instruction.snake),
			emit_instruction(instruction, &client_crate),
		);
	}

	if !model.accounts.is_empty() {
		files.insert("src/fetch.rs".to_string(), emit_fetch(model, &client_crate));
	}

	Ok(files)
}

/// Render scaffold files written only when the destination is created.
pub(crate) fn render_scaffold(
	model: &CliModel,
	client_package: &str,
	client_path: &str,
) -> BTreeMap<String, String> {
	let mut files = BTreeMap::new();
	files.insert(
		"Cargo.toml".to_string(),
		emit_manifest(model, client_package, client_path),
	);
	files.insert("README.md".to_string(), emit_readme(model));
	files
}

