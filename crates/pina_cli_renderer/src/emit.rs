/// Errors surfaced by every generated command. Programs without
/// accounts or byte flags never construct some variants; the blanket
/// allow keeps the emitted file warning-free under `-D warnings`.
#[allow(dead_code)]
#[derive(Debug, Error)]
pub enum CliError {
	#[error("`{value}` is not a valid RPC endpoint; expected mainnet, devnet, testnet, localhost, or an http(s) URL")]
	InvalidEndpoint { value: String },

	#[error("plaintext `http://` endpoints are only allowed on localhost; use https for remote clusters")]
	InsecureEndpoint { value: String },

	#[error("`{flag}` must be a base58 public key: {source}")]
	InvalidPubkey { flag: String, source: ParsePubkeyError },

	#[error("`{flag}` must be valid base58: {source}")]
	InvalidBase58 {
		flag: String,
		source: bs58::decode::Error,
	},

	#[error("`{flag}` must hold exactly {expected} bytes, found {actual}")]
	InvalidByteLength {
		flag: String,
		expected: usize,
		actual: usize,
	},

	#[error("could not load payer keypair `{path}`: {message}")]
	Keypair { path: PathBuf, message: String },

	#[error("RPC request failed: {0}")]
	Rpc(#[from] ClientError),

	#[error("the transaction failed: {0}")]
	TransactionFailed(String),

	#[error("account `{address}` was not found")]
	AccountNotFound { address: String },

	#[error("account `{address}` belongs to `{owner}`, not the configured program")]
	AccountOwnerMismatch { address: String, owner: String },

	#[error("account `{address}` could not be decoded: {message}")]
	AccountDecode { address: String, message: String },

	#[error("instruction data is invalid: {message}")]
	InvalidData { message: String },

	#[error("derive `--address` explicitly or provide PDA seed `{seed}` for `{account}`")]
	MissingSeed { account: String, seed: String },
}

/// Shared runtime for generated CLIs. Helpers unused by a given program
/// (e.g. fetch in a no-account program) are `#[allow(dead_code)]` so the
/// emitted context stays warning-free under `-D warnings`.
#[allow(dead_code)]
pub struct CliContext {
	pub rpc: RpcClient,
	pub payer: Keypair,
	pub program_address: Pubkey,
	pub simulate: bool,
	pub json: bool,
	cluster: &'static str,
}

impl CliContext {
	/// Build the context from the parsed global flags.
	pub fn new(
		url: &str,
		keypair: &str,
		program_address: Pubkey,
		simulate: bool,
		json: bool,
	) -> Result<Self, CliError> {
		let (endpoint, cluster) = resolve_endpoint(url)?;
		let payer = load_keypair(keypair)?;

		Ok(Self {
			rpc: RpcClient::new(endpoint),
			payer,
			program_address,
			simulate,
			json,
			cluster,
		})
	}

	/// The payer public key.
	#[must_use]
	pub fn payer_pubkey(&self) -> Pubkey {
		self.payer.pubkey()
	}

	/// Parse and validate a base58 public key flag.
	pub fn pubkey(flag: &str, value: &str) -> Result<Pubkey, CliError> {
		value
			.parse()
			.map_err(|source| CliError::InvalidPubkey {
				flag: flag.to_string(),
				source,
			})
	}

	/// Decode a capacity-bounded byte flag from base58.
	pub fn byte_vec(flag: &str, value: &str) -> Result<Vec<u8>, CliError> {
		bs58::decode(value)
			.into_vec()
			.map_err(|source| CliError::InvalidBase58 {
				flag: flag.to_string(),
				source,
			})
	}

	/// Decode an exact-length byte flag from base58.
	pub fn bytes<const N: usize>(flag: &str, value: &str) -> Result<[u8; N], CliError> {
		let decoded = bs58::decode(value)
			.into_vec()
			.map_err(|source| CliError::InvalidBase58 {
				flag: flag.to_string(),
				source,
			})?;

		decoded.try_into().map_err(|actual: Vec<u8>| {
			CliError::InvalidByteLength {
				flag: flag.to_string(),
				expected: N,
				actual: actual.len(),
			}
		})
	}

	/// Send or simulate one instruction, printing the result.
	pub fn send(&self, instruction: Instruction) -> Result<(), CliError> {
		let mut instruction = instruction;
		instruction.program_id = self.program_address;
		let blockhash = self.rpc.get_latest_blockhash()?;
		let transaction = Transaction::new_signed_with_payer(
			&[instruction],
			Some(&self.payer.pubkey()),
			&[&self.payer],
			blockhash,
		);

		if self.simulate {
			return self.simulate(&transaction);
		}

		let signature = self.rpc.send_and_confirm_transaction(&transaction)?.to_string();
		if self.json {
			println!("{{\"signature\":\"{signature}\"}}");
		} else {
			println!("Signature: {signature}");
			if !self.cluster.is_empty() {
				println!(
					"https://explorer.solana.com/tx/{signature}?cluster={}",
					self.cluster
				);
			}
		}
		Ok(())
	}

	fn simulate(&self, transaction: &Transaction) -> Result<(), CliError> {
		let simulation = self.rpc.simulate_transaction(transaction)?.value;
		let logs = simulation.logs.clone();
		let consumed = simulation.units_consumed;

		if self.json {
			println!(
				"{}",
				serde_json::json!({ "logs": logs, "unitsConsumed": consumed })
			);
		} else {
			for log in logs.iter().flatten() {
				println!("{log}");
			}
			if let Some(consumed) = consumed {
				println!("Consumed {consumed} compute units");
			}
		}

		if let Some(failure) = simulation.err {
			let logs = logs.unwrap_or_default().join("\n");
			return Err(CliError::TransactionFailed(format!("{failure}\n{logs}")));
		}
		Ok(())
	}

	/// Fetch one owned account, verifying its owner matches the program.
	pub fn fetch_account(&self, address: &Pubkey) -> Result<Vec<u8>, CliError> {
		let account = self.rpc.get_account(address)?;

		if account.owner != self.program_address {
			return Err(CliError::AccountOwnerMismatch {
				address: address.to_string(),
				owner: account.owner.to_string(),
			});
		}
		Ok(account.data)
	}
}

/// Resolve a cluster name or URL, rejecting plaintext remote endpoints.
///
/// # Errors
///
/// Returns an error for endpoints that are neither https nor localhost http.
pub fn resolve_endpoint(value: &str) -> Result<(String, &'static str), CliError> {
	let (endpoint, cluster): (&str, &str) = match value {
		"mainnet" | "mainnet-beta" => (MAINNET_ENDPOINT, ""),
		"devnet" => (DEVNET_ENDPOINT, "devnet"),
		"testnet" => (TESTNET_ENDPOINT, "testnet"),
		"localhost" | "localnet" => (LOCALNET_ENDPOINT, "custom"),
		custom => (custom, "custom"),
	};

	if !endpoint_is_secure(&endpoint) {
		return Err(CliError::InsecureEndpoint {
			value: value.to_string(),
		});
	}

	Ok((endpoint.to_string(), cluster))
}

/// Whether an endpoint may be used as-is: any `https://` URL, or plaintext
/// `http://` pointed at exactly `localhost`, `127.0.0.1`, or `[::1]`.
///
/// The host is read from the URL authority after rejecting userinfo, so
/// lookalikes such as `http://localhost.evil.com` or
/// `http://127.0.0.1@evil.com` do not count as local.
fn endpoint_is_secure(endpoint: &str) -> bool {
	let lowercase = endpoint.to_ascii_lowercase();
	if lowercase.starts_with("https://") {
		return true;
	}
	let Some(rest) = lowercase.strip_prefix("http://") else {
		return false;
	};
	let authority = rest.split(['/', '?', '#']).next().unwrap_or_default();
	if authority.contains('@') {
		return false;
	}
	let host = endpoint_authority_host(authority);
	matches!(host, "localhost" | "127.0.0.1" | "::1")
}

/// The host portion of a URL authority, with the port and any IPv6 brackets
/// removed.
fn endpoint_authority_host(authority: &str) -> &str {
	if let Some(inner) = authority.strip_prefix('[') {
		let end = inner.find(']').unwrap_or(inner.len());
		return &inner[..end];
	}
	match authority.rsplit_once(':') {
		Some((host, _port)) => host,
		None => authority,
	}
}

