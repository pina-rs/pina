fn emit_main(model: &CliModel) -> String {
	let has_fetch = !model.accounts.is_empty();

	let mut commands = String::default();
	for instruction in &model.instructions {
		commands.push_str(&doc_lines(&instruction.docs, 1));
		commands.push('\n');
		commands.push_str(&format!(
			"\t{}(commands::{}Args),\n",
			instruction.pascal, instruction.pascal
		));
	}

	let mut dispatch = String::default();
	for instruction in &model.instructions {
		dispatch.push_str(&format!(
			"\t\tCommand::{}(args) => commands::{}::run(&context, args),\n",
			instruction.pascal, instruction.snake
		));
	}

	tpl(
		MAIN_TEMPLATE,
		&[
			("@@HEADER@@", GENERATED_HEADER.to_string()),
			("@@PROGRAM_CAMEL@@", model.program_camel.clone()),
			("@@ABOUT@@", model.about.clone()),
			("@@BIN_NAME@@", model.bin_name.clone()),
			("@@PROGRAM_ADDRESS@@", model.program_address.clone()),
			(
				"@@FETCH_MOD@@",
				if has_fetch {
					"mod fetch;\n".to_string()
				} else {
					String::default()
				},
			),
			("@@COMMANDS@@", commands),
			(
				"@@FETCH_VARIANT@@",
				if has_fetch {
					{
						"\t/// Fetch and decode a program \
						 account.\n\t#[command(subcommand)]\n\tFetch(fetch::Command),\n"
							.to_string()
					}
				} else {
					String::default()
				},
			),
			("@@DISPATCH@@", dispatch),
			(
				"@@FETCH_DISPATCH@@",
				if has_fetch {
					{
						"\t\tCommand::Fetch(command) => fetch::run(&context, command),\n"
							.to_string()
					}
				} else {
					String::default()
				},
			),
		],
	)
}

fn emit_commands_mod(model: &CliModel) -> String {
	let mut output = format!("{GENERATED_HEADER}\n");
	for instruction in &model.instructions {
		output.push_str(&format!("pub mod {};\n", instruction.snake));
	}
	output.push('\n');
	for instruction in &model.instructions {
		output.push_str(&format!(
			"pub use {}::{}Args;\n",
			instruction.snake, instruction.pascal
		));
	}
	output
}

