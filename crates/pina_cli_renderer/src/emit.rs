fn emit_instruction(instruction: &InstructionModel, client_crate: &str) -> String {
	let uses_pubkey = instruction.accounts.iter().any(|account| {
		matches!(
			account.resolution,
			Resolution::Pda { .. } | Resolution::Constant(_)
		)
	});
	let pubkey_import = if uses_pubkey {
		"use solana_sdk::pubkey::Pubkey;\n".to_string()
	} else {
		String::default()
	};
	let mut flag_fields = String::default();

	for arg in &instruction.args {
		let ty = match arg.kind {
			ArgKind::Number { rust_ty } => rust_ty.to_string(),
			ArgKind::Bool => "bool".to_string(),
			ArgKind::Pubkey
			| ArgKind::FixedBytes { .. }
			| ArgKind::ByteVec { .. }
			| ArgKind::FixedString { .. } => "String".to_string(),
		};
		let docs = doc_lines(&arg.docs, 1);
		if !docs.is_empty() {
			flag_fields.push_str(&docs);
			flag_fields.push('\n');
		}
		flag_fields.push_str(&format!("\t#[arg(long)]\n\t{}: {ty},\n", arg.snake));
	}

	for account in &instruction.accounts {
		if matches!(account.resolution, Resolution::Constant(_)) {
			continue;
		}
		let hint = match account.resolution {
			Resolution::Pda { .. } => " [default: derived]",
			Resolution::Payer => " [default: payer]",
			Resolution::Required | Resolution::Constant(_) => "",
		};
		let docs = if account.docs.is_empty() {
			format!("The `{}` account.", account.snake)
		} else {
			account.docs.join(" ")
		};
		let flag_ty = if matches!(account.resolution, Resolution::Required) {
			"String"
		} else {
			"Option<String>"
		};
		flag_fields.push_str(&format!("\t/// {}{hint}\n", single_line(&docs)));
		flag_fields.push_str(&format!(
			"\t#[arg(long)]\n\t{}: {flag_ty},\n",
			account.snake
		));
	}

	let mut locals = String::default();
	for arg in &instruction.args {
		match arg.kind {
			ArgKind::Pubkey => {
				locals.push_str(&format!(
					"\tlet {name} = CliContext::pubkey(\"--{name}\", &args.{name})?;\n",
					name = arg.snake
				));
			}
			ArgKind::FixedBytes { size } => {
				locals.push_str(&format!(
					"\tlet {name} = CliContext::bytes::<{size}>(\"--{name}\", &args.{name})?;\n",
					name = arg.snake
				));
			}
			ArgKind::ByteVec { .. } => {
				locals.push_str(&format!(
					"\tlet {name} = CliContext::byte_vec(\"--{name}\", &args.{name})?;\n",
					name = arg.snake
				));
			}
			_ => {}
		}
	}

	for account in &instruction.accounts {
		match &account.resolution {
			Resolution::Constant(_) => {}
			Resolution::Payer => {
				locals.push_str(&format!(
					"\tlet {name} = match &args.{name} {{\n\t\tSome(value) => \
					 CliContext::pubkey(\"--{name}\", value)?,\n\t\tNone => \
					 context.payer_pubkey(),\n\t}};\n",
					name = account.snake
				));
			}
			Resolution::Pda { seeds } => {
				locals.push_str(&format!(
					"\tlet {name} = match &args.{name} {{\n\t\tSome(value) => \
					 CliContext::pubkey(\"--{name}\", value)?,\n\t\tNone => \
					 Pubkey::find_program_address(\n\t\t\t&[{seeds}],\n\t\t\t&context.\
					 program_address,\n\t\t)\n\t\t.0,\n\t}};\n",
					name = account.snake,
					seeds = seed_expressions(seeds),
				));
			}
			Resolution::Required => {
				locals.push_str(&format!(
					"\tlet {name} = CliContext::pubkey(\"--{name}\", &args.{name})?;\n",
					name = account.snake
				));
			}
		}
	}

	let mut literal = String::default();
	for account in &instruction.accounts {
		let value = match &account.resolution {
			Resolution::Constant(address) => format!("Pubkey::from_str_const({address:?})"),
			_ => account.snake.clone(),
		};
		let value = if account.is_optional {
			format!("Some({value})")
		} else {
			value
		};
		literal.push_str(&format!("\t\t{}: {value},\n", account.snake));
	}

	let data_setup = data_setup_for(instruction);

	tpl(
		INSTRUCTION_TEMPLATE,
		&[
			("@@HEADER@@", GENERATED_HEADER.to_string()),
			("@@CLIENT_CRATE@@", client_crate.to_string()),
			("@@PUBKEY_IMPORT@@", pubkey_import),
			("@@ACCOUNTS_STRUCT@@", instruction.accounts_struct.clone()),
			("@@DATA_IDENT@@", instruction.data_ident.clone()),
			("@@PASCAL@@", instruction.pascal.clone()),
			(
				"@@ARGS@@",
				if instruction.args.is_empty() && instruction.accounts.is_empty() {
					"_args".to_string()
				} else {
					"args".to_string()
				},
			),
			("@@FLAG_FIELDS@@", flag_fields),
			("@@LOCALS@@", locals),
			("@@DATA_SETUP@@", data_setup),
			("@@LITERAL@@", literal),
		],
	)
}

fn data_setup_for(instruction: &InstructionModel) -> String {
	if !instruction.has_data_args() {
		return format!(
			"\tlet data = {ident}::new(|_data| {{}})\n\t.map_err(|_| CliError::InvalidData \
			 {{\n\t\tmessage: \"instruction data rejected the provided \
			 arguments\".to_string(),\n\t}})?;\n",
			ident = instruction.data_ident
		);
	}

	let mut assignments = String::default();
	let mut fallible = false;
	for arg in &instruction.args {
		match arg.kind {
			ArgKind::Number {
				rust_ty: "u8" | "i8",
			} => {
				assignments.push_str(&format!("\t\tdata.{} = args.{};\n", arg.snake, arg.snake));
			}
			ArgKind::Number { .. } | ArgKind::Bool => {
				assignments.push_str(&format!(
					"\t\tdata.{}.set(args.{});\n",
					arg.snake, arg.snake
				));
			}
			ArgKind::Pubkey | ArgKind::FixedBytes { .. } => {
				assignments.push_str(&format!("\t\tdata.{} = {};\n", arg.snake, arg.snake));
			}
			ArgKind::FixedString { .. } => {
				fallible = true;
				assignments.push_str(&format!(
					"\t\tif let Err(error) = data.{name}.try_set(&args.{name}) {{\n\t\t\tinvalid \
					 = Some(format!(\"--{name}: {{error}}\"));\n\t\t}}\n",
					name = arg.snake
				));
			}
			ArgKind::ByteVec { .. } => {
				fallible = true;
				assignments.push_str(&format!(
					"\t\tif let Err(error) = data.{name}.try_set_from_slice(&{name}) \
					 {{\n\t\t\tinvalid = Some(format!(\"--{name}: {{error}}\"));\n\t\t}}\n",
					name = arg.snake
				));
			}
		}
	}

	let capture = if fallible {
		"\tlet mut invalid: Option<String> = None;\n".to_string()
	} else {
		String::default()
	};
	let recheck = if fallible {
		{
			"\tif let Some(message) = invalid {\n\t\treturn Err(CliError::InvalidData { message \
			 });\n\t}\n"
				.to_string()
		}
	} else {
		String::default()
	};

	format!(
		"{capture}\tlet data = {ident}::new(|data| {{\n{assignments}\t}})\n\t.map_err(|_| \
		 CliError::InvalidData {{\n\t\tmessage: \"instruction data rejected the provided \
		 arguments\".to_string(),\n\t}})?;\n{recheck}",
		capture = capture,
		ident = instruction.data_ident,
		assignments = assignments,
		recheck = recheck,
	)
}

fn constant_seed_expression(constant: &SeedModel) -> String {
	match constant {
		SeedModel::Utf8(value) => format!("{value:?}.as_bytes()"),
		SeedModel::ConstPubkey(value) => format!("Pubkey::from_str_const({value:?}).as_ref()"),
		SeedModel::ConstNumber { value, rust_ty } => {
			format!("{value}_{rust_ty}.to_le_bytes().as_ref()")
		}
		_ => unreachable!("constant fetch seeds are always constants"),
	}
}

fn seed_expressions(seeds: &[SeedModel]) -> String {
	let mut parts = Vec::new();
	for seed in seeds {
		parts.push(match seed {
			SeedModel::Utf8(value) => format!("{value:?}.as_bytes()"),
			SeedModel::ConstPubkey(value) => {
				format!("Pubkey::from_str_const({value:?}).as_ref()")
			}
			SeedModel::ConstNumber { value, rust_ty } => {
				format!("{value}_{rust_ty}.to_le_bytes().as_ref()")
			}
			SeedModel::Account(name) => format!("{name}.as_ref()"),
			SeedModel::Arg { arg, kind } => {
				match kind {
					ArgKind::Number { rust_ty } => {
						format!("{arg}_{rust_ty}.to_le_bytes().as_ref()")
					}
					_ => format!("{arg}.as_ref()"),
				}
			}
		});
	}
	parts.join(", ")
}

