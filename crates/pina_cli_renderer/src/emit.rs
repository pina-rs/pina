fn emit_fetch(model: &CliModel, client_crate: &str) -> String {
	let mut variants = String::default();
	let mut args_structs = String::default();
	let mut dispatch = String::default();
	let mut fetchers = String::default();
	let mut json_fns = String::default();

	for account in &model.accounts {
		let args_ident = format!("{}Args", account.pascal);

		variants.push_str(&doc_lines(&account.docs, 1));
		variants.push('\n');
		variants.push_str(&format!("\t{}({args_ident}),\n", account.pascal));

		let mut fields = String::from(
			"\t/// Account address; overrides PDA derivation.\n\t#[arg(long)]\n\taddress: \
			 Option<String>,\n",
		);
		if let Some(seeds) = &account.seeds {
			for seed in seeds.iter().filter(|seed| seed.constant.is_none()) {
				let ty = match seed.kind {
					ArgKind::Number { rust_ty } => rust_ty.to_string(),
					ArgKind::Bool => "bool".to_string(),
					_ => "String".to_string(),
				};
				fields.push_str(&format!(
					"\t/// PDA seed `{}`.\n\t#[arg(long)]\n\t{}: Option<{ty}>,\n",
					seed.snake, seed.snake,
				));
			}
		}
		args_structs.push_str(&format!(
			"#[derive(Debug, Args)]\npub struct {args_ident} {{\n{fields}}}\n\n"
		));

		dispatch.push_str(&format!(
			"\t\tCommand::{}(args) => fetch_{}(context, args),\n",
			account.pascal, account.snake,
		));

		let derivation = account
			.seeds
			.as_ref()
			.map(|seeds| {
				seeds
					.iter()
					.filter(|seed| seed.constant.is_none())
					.map(|seed| {
						match seed.kind {
							ArgKind::Pubkey => {
								format!(
									"\t\t\t\tlet {name} = match &args.{name} \
									 {{\n\t\t\t\t\tSome(value) => \
									 CliContext::pubkey(\"--{name}\", value)?,\n\t\t\t\t\tNone => \
									 return Err(CliError::MissingSeed {{ account: \
									 \"{kebab}\".to_string(), seed: \"--{name}\".to_string() \
									 }}),\n\t\t\t\t}};\n",
									name = seed.snake,
									kebab = account.kebab,
								)
							}
							ArgKind::Number { .. } => {
								format!(
									"\t\t\t\tlet {name} = args.{name}.ok_or_else(|| \
									 CliError::MissingSeed {{ account: \"{kebab}\".to_string(), \
									 seed: \"--{name}\".to_string() }})?;\n",
									name = seed.snake,
									kebab = account.kebab,
								)
							}
							_ => String::default(),
						}
					})
					.collect::<String>()
			})
			.unwrap_or_default();

		let seed_refs = account
			.seeds
			.as_ref()
			.map(|seeds| {
				seeds
					.iter()
					.map(|seed| {
						match &seed.constant {
							Some(constant) => constant_seed_expression(constant),
							None => {
								match seed.kind {
									ArgKind::Number { .. } => {
										format!("{}_bytes.as_ref()", seed.snake)
									}
									_ => format!("{}.as_ref()", seed.snake),
								}
							}
						}
					})
					.collect::<Vec<_>>()
					.join(", ")
			})
			.unwrap_or_default();

		let seed_bindings = account
			.seeds
			.as_ref()
			.map(|seeds| {
				seeds
					.iter()
					.filter(|seed| seed.constant.is_none())
					.filter_map(|seed| {
						match seed.kind {
							ArgKind::Number { .. } => {
								Some(format!(
									"\t\t\tlet {name}_bytes = {name}.to_le_bytes();\n",
									name = seed.snake,
								))
							}
							_ => None,
						}
					})
					.collect::<String>()
			})
			.unwrap_or_default();
		let derive_expr = if account.seeds.is_some() {
			format!(
				"{seed_bindings}\t\t\tlet seeds: &[&[u8]] = \
				 &[{seed_refs}];\n\t\t\tPubkey::find_program_address(seeds, \
				 &context.program_address).0\n",
			)
		} else {
			format!(
				"\t\t\treturn Err(CliError::MissingSeed {{\n\t\t\t\taccount: \
				 \"{kebab}\".to_string(),\n\t\t\t\tseed: \"--address\".to_string(),\n\t\t\t}})\n",
				kebab = account.kebab,
			)
		};

		fetchers.push_str(&tpl(
			r#"fn fetch_@@SNAKE@@(context: &CliContext, args: @@PASCAL@@Args) -> Result<(), CliError> {
	let address = match &args.address {
		Some(value) => CliContext::pubkey("--address", value)?,
		None => {
@@DERIVATION@@@@DERIVE_EXPR@@		}
	};
	let data = context.fetch_account(&address)?;
	let value = match @@CLIENT_CRATE@@::accounts::@@PASCAL@@::from_bytes(&data) {
		Ok(account) => @@SNAKE@@_json(@@ACCOUNT_BORROW@@account),
		Err(error) => return Err(CliError::AccountDecode {
			address: address.to_string(),
			message: error.to_string(),
		}),
	};
	print_value(context.json, "@@KEBAB@@", &address, &value);
	Ok(())
}

"#,
			&[
				("@@SNAKE@@", account.snake.clone()),
				("@@PASCAL@@", account.pascal.clone()),
				("@@KEBAB@@", account.kebab.clone()),
				("@@CLIENT_CRATE@@", client_crate.to_string()),
				("@@DERIVATION@@", derivation),
				("@@DERIVE_EXPR@@", derive_expr),
				// Compact accounts decode into an owned `…Ref<'_>` value, so the
				// helper needs `&value`; fixed-layout accounts already decode
				// into a reference and borrowing again is redundant.
				(
					"@@ACCOUNT_BORROW@@",
					if account.compact { "&" } else { "" }.to_string(),
				),
			],
		));

		let mut entries = String::default();
		for field in &account.fields {
			let vec_accessor = |receiver: &str| {
				match field.kind {
					FieldKind::Vec {
						plain_element: true,
					} => format!("{receiver}.to_vec()"),
					_ => format!("{receiver}.iter().map(|value| value.get()).collect::<Vec<_>>()"),
				}
			};
			let accessor = if account.compact {
				match field.kind {
					FieldKind::String | FieldKind::OptionString => {
						format!("account.{}()", field.snake)
					}
					FieldKind::Vec { .. } => {
						vec_accessor(format!("account.{}()", field.snake).as_str())
					}
					FieldKind::Number { plain: true } => format!("account.{}", field.snake),
					FieldKind::Number { plain: false } | FieldKind::Bool => {
						format!("account.{}.get()", field.snake)
					}
					FieldKind::Option => {
						format!("account.{}.get().map(|value| value.get())", field.snake)
					}
					FieldKind::Pubkey | FieldKind::FixedBytes => {
						format!("account.{}.to_string()", field.snake)
					}
				}
			} else {
				match field.kind {
					FieldKind::Number { plain: true } => format!("account.{}", field.snake),
					FieldKind::Number { plain: false } | FieldKind::Bool => {
						format!("account.{}.get()", field.snake)
					}
					FieldKind::Pubkey => format!("account.{}.to_string()", field.snake),
					FieldKind::String => format!("account.{}.as_str()", field.snake),
					FieldKind::FixedBytes => {
						format!(
							"account.{0}.iter().map(|byte| \
							 format!(\"{{byte:02x}}\")).collect::<String>()",
							field.snake
						)
					}
					FieldKind::Option => {
						format!("account.{}.get().map(|value| value.get())", field.snake)
					}
					FieldKind::OptionString => {
						format!("account.{}.get().map(|value| value.as_str())", field.snake)
					}
					FieldKind::Vec { .. } => {
						vec_accessor(format!("account.{}", field.snake).as_str())
					}
				}
			};
			entries.push_str(&format!("\t\t\"{}\": {},\n", field.snake, accessor));
		}

		let view = if account.compact {
			format!("{}Ref<'_>", account.pascal)
		} else {
			format!("{}Zc", account.pascal)
		};
		json_fns.push_str(&format!(
			"fn {snake}_json(account: &{client_crate}::accounts::{view}) -> Value \
			 {{\n\tjson!({{\n{entries}\t}})\n}}\n\n",
			snake = account.snake,
			client_crate = client_crate,
		));
	}

	tpl(
		FETCH_TEMPLATE,
		&[
			("@@HEADER@@", GENERATED_HEADER.to_string()),
			("@@CLIENT_CRATE@@", client_crate.to_string()),
			("@@VARIANTS@@", variants),
			("@@ARGS_STRUCTS@@", args_structs),
			("@@DISPATCH@@", dispatch),
			("@@FETCHERS@@", fetchers),
			("@@JSON_FNS@@", json_fns),
		],
	)
}

