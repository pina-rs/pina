/// Validates Dart renderer inputs before any Dart source is emitted.
///
/// The workspace pins the renderer patch needed for Codama offset nodes so
/// compact multi-tail layouts retain their shared-header prefixes. A separate
/// post-render pass adds validation that Codama 0.13.2 cannot express.
pub fn validate_dart_client_idls(
	output_root: &Path,
	programs: &[String],
	idl_paths: &[impl AsRef<Path>],
) -> Result<(), CodamaError> {
	if programs.len() != idl_paths.len() {
		return Err(dart_error(
			output_root,
			format!(
				"received {} programs but {} IDL paths",
				programs.len(),
				idl_paths.len(),
			),
		));
	}

	for idl_path in idl_paths {
		let idl_path = idl_path.as_ref();
		let idl_source = std::fs::read_to_string(idl_path).map_err(|source| {
			CodamaError::DartClient {
				path: idl_path.to_path_buf(),
				source: Box::new(source),
			}
		})?;
		let idl: Value = serde_json::from_str(&idl_source).map_err(|source| {
			CodamaError::DartClient {
				path: idl_path.to_path_buf(),
				source: Box::new(source),
			}
		})?;

		validate_supported_types(&idl, idl_path)?;
		let root: RootNode =
			serde_json::from_value(idl).map_err(|error| dart_error(idl_path, error.to_string()))?;
		CompactCapacityIndex::read(&root.program).map_err(|error| dart_error(idl_path, error))?;
	}

	Ok(())
}

#[derive(Clone, Debug, Eq, PartialEq)]
enum DartFixedLayout {
	Bool,
	Enum {
		byte_width: usize,
		values: Vec<u32>,
	},
	Option {
		prefix_bytes: usize,
		item: Option<Box<Self>>,
	},
	String {
		prefix_bytes: usize,
		capacity: usize,
	},
	Vec {
		prefix_bytes: usize,
		capacity: usize,
		item_bytes: usize,
		item: Option<Box<Self>>,
	},
}

impl DartFixedLayout {
	fn render(&self) -> String {
		match self {
			Self::Bool => "const PinaPodBoolLayout()".to_owned(),
			Self::Enum { byte_width, values } => {
				let values = values
					.iter()
					.map(|value| format!("BigInt.from({value})"))
					.collect::<Vec<_>>()
					.join(", ");
				format!("PinaPodEnumLayout({byte_width}, [{values}])")
			}
			Self::Option { prefix_bytes, item } => {
				let item = item
					.as_deref()
					.map_or_else(|| "null".to_owned(), Self::render);
				format!("PinaPodOptionLayout({prefix_bytes}, {item})")
			}
			Self::String {
				prefix_bytes,
				capacity,
			} => format!("PinaPodStringLayout({prefix_bytes}, {capacity})"),
			Self::Vec {
				prefix_bytes,
				capacity,
				item_bytes,
				item,
			} => {
				let item = item
					.as_deref()
					.map_or_else(|| "null".to_owned(), Self::render);
				format!("PinaPodVecLayout({prefix_bytes}, {capacity}, {item_bytes}, {item})")
			}
		}
	}
}

fn dart_raw_layout(node: &TypeNode, program: &ProgramNode) -> Option<DartFixedLayout> {
	match node {
		TypeNode::FixedSize(fixed) => dart_fixed_layout(&fixed.r#type, fixed.size, program),
		TypeNode::Option(option) => dart_raw_layout(&option.item, program),
		TypeNode::PreOffset(offset) => dart_raw_layout(&offset.r#type, program),
		TypeNode::PostOffset(offset) => dart_raw_layout(&offset.r#type, program),
		_ => None,
	}
}

fn dart_fixed_layout(
	node: &TypeNode,
	total_size: usize,
	program: &ProgramNode,
) -> Option<DartFixedLayout> {
	match node {
		TypeNode::Boolean(_) => Some(DartFixedLayout::Bool),
		TypeNode::FixedSize(fixed) => dart_fixed_layout(&fixed.r#type, fixed.size, program),
		TypeNode::SizePrefix(prefix) if matches!(prefix.r#type.as_ref(), TypeNode::String(_)) => {
			let prefix_bytes = number_node_size(prefix.prefix.get_nested_type_node())?;
			Some(DartFixedLayout::String {
				prefix_bytes,
				capacity: total_size.checked_sub(prefix_bytes)?,
			})
		}
		TypeNode::Array(array) => {
			let CountNode::Prefixed(count) = array.count.as_ref() else {
				return None;
			};
			let prefix_bytes = number_node_size(count.prefix.get_nested_type_node())?;
			let item_bytes = dart_type_size(&array.item, program)?;
			let payload_bytes = total_size.checked_sub(prefix_bytes)?;
			if item_bytes == 0 || payload_bytes % item_bytes != 0 {
				return None;
			}
			Some(DartFixedLayout::Vec {
				prefix_bytes,
				capacity: payload_bytes / item_bytes,
				item_bytes,
				item: dart_fixed_layout(&array.item, item_bytes, program).map(Box::new),
			})
		}
		TypeNode::Option(option) if option.fixed == Some(true) => {
			let prefix_bytes = number_node_size(option.prefix.get_nested_type_node())?;
			let item_bytes = total_size.checked_sub(prefix_bytes)?;
			Some(DartFixedLayout::Option {
				prefix_bytes,
				item: dart_fixed_layout(&option.item, item_bytes, program).map(Box::new),
			})
		}
		TypeNode::Link(link) => {
			let defined = program
				.defined_types
				.iter()
				.find(|defined| defined.name == link.name)?;
			let TypeNode::Enum(enum_type) = defined.r#type.as_ref() else {
				return None;
			};
			let byte_width = number_node_size(enum_type.size.get_nested_type_node())?;
			let values = enum_type
				.variants
				.iter()
				.enumerate()
				.map(|(index, variant)| {
					let discriminator = match variant {
						EnumVariantTypeNode::Empty(variant) => variant.discriminator,
						EnumVariantTypeNode::Struct(variant) => variant.discriminator,
						EnumVariantTypeNode::Tuple(variant) => variant.discriminator,
					};
					discriminator.unwrap_or(u32::try_from(index).unwrap_or(u32::MAX))
				})
				.collect();
			Some(DartFixedLayout::Enum { byte_width, values })
		}
		_ => None,
	}
}

fn dart_type_size(node: &TypeNode, program: &ProgramNode) -> Option<usize> {
	match node {
		TypeNode::Number(number) => number_node_size(number),
		TypeNode::Boolean(_) => Some(1),
		TypeNode::PublicKey(_) => Some(32),
		TypeNode::FixedSize(fixed) => Some(fixed.size),
		TypeNode::Option(option) if option.fixed == Some(true) => {
			let prefix = number_node_size(option.prefix.get_nested_type_node())?;
			prefix.checked_add(dart_type_size(&option.item, program)?)
		}
		TypeNode::Link(link) => {
			let defined = program
				.defined_types
				.iter()
				.find(|defined| defined.name == link.name)?;
			match defined.r#type.as_ref() {
				TypeNode::Enum(enum_type) => {
					number_node_size(enum_type.size.get_nested_type_node())
				}
				_ => None,
			}
		}
		_ => None,
	}
}

fn number_node_size(number: &codama_nodes::NumberTypeNode) -> Option<usize> {
	match number.format {
		NumberFormat::U8 | NumberFormat::I8 => Some(1),
		NumberFormat::U16 | NumberFormat::I16 => Some(2),
		NumberFormat::U32 | NumberFormat::I32 => Some(4),
		NumberFormat::U64 | NumberFormat::I64 => Some(8),
		NumberFormat::U128 | NumberFormat::I128 => Some(16),
		NumberFormat::F32 | NumberFormat::F64 | NumberFormat::ShortU16 => None,
	}
}

/// Adds `PinaPod` capacity guards to rendered Dart codecs and removes the
/// Codama 0.13.2 compatibility marker artifacts from the public client.
pub fn harden_generated_dart_clients(
	output_root: &Path,
	programs: &[String],
	idl_paths: &[impl AsRef<Path>],
) -> Result<(), CodamaError> {
	if programs.len() != idl_paths.len() {
		return Err(dart_error(
			output_root,
			format!(
				"received {} programs but {} IDL paths",
				programs.len(),
				idl_paths.len(),
			),
		));
	}

	for (program, idl_path) in programs.iter().zip(idl_paths) {
		let idl_path = idl_path.as_ref();
		let source = std::fs::read_to_string(idl_path).map_err(|source| {
			CodamaError::DartClient {
				path: idl_path.to_path_buf(),
				source: Box::new(source),
			}
		})?;
		let root: RootNode = serde_json::from_str(&source)
			.map_err(|error| dart_error(idl_path, error.to_string()))?;
		let capacity_index = CompactCapacityIndex::read(&root.program)
			.map_err(|error| dart_error(idl_path, error))?;
		let generated = output_root.join("lib/src/generated").join(program);

		strip_dart_capacity_marker_artifacts(&generated, &capacity_index)?;
		let mut needs_helper = !capacity_index.capacities().is_empty();
		for account in &root.program.accounts {
			let path = generated
				.join("accounts")
				.join(format!("{}.dart", account.name.as_ref().to_snake_case()));
			let capacities = capacity_index
				.capacities()
				.iter()
				.filter(|((name, _), _)| name == account.name.as_ref())
				.map(|((_, field), capacity)| (field.clone(), *capacity))
				.collect::<Vec<_>>();
			let layouts = account
				.data
				.get_nested_type_node()
				.fields
				.iter()
				.filter_map(|field| {
					dart_raw_layout(&field.r#type, &root.program)
						.map(|layout| (field.name.as_ref().to_owned(), layout))
				})
				.collect::<Vec<_>>();
			if capacities.is_empty() && layouts.is_empty() {
				continue;
			}
			needs_helper = true;
			harden_dart_file(&path, &capacities, &layouts)?;
		}

		for instruction in &root.program.instructions {
			let path = generated.join("instructions").join(format!(
				"{}.dart",
				instruction.name.as_ref().to_snake_case()
			));
			let layouts = instruction
				.arguments
				.iter()
				.filter_map(|argument| {
					dart_raw_layout(&argument.r#type, &root.program)
						.map(|layout| (argument.name.as_ref().to_owned(), layout))
				})
				.collect::<Vec<_>>();
			if layouts.is_empty() {
				continue;
			}
			needs_helper = true;
			harden_dart_file(&path, &[], &layouts)?;
		}

		if needs_helper {
			let helper_path = generated.join("pina_pod_codecs.dart");
			std::fs::write(&helper_path, DART_HELPER_MODULE).map_err(|source| {
				CodamaError::DartClient {
					path: helper_path,
					source: Box::new(source),
				}
			})?;
		}

		emit_dart_migration_helpers(&generated, program, &root)?;
	}

	Ok(())
}

fn harden_dart_file(
	path: &Path,
	capacities: &[(String, CompactCapacity)],
	layouts: &[(String, DartFixedLayout)],
) -> Result<(), CodamaError> {
	let source = std::fs::read_to_string(path).map_err(|source| {
		CodamaError::DartClient {
			path: path.to_path_buf(),
			source: Box::new(source),
		}
	})?;
	let hardened = harden_dart_codec_source(&source, capacities, layouts);
	std::fs::write(path, hardened).map_err(|source| {
		CodamaError::DartClient {
			path: path.to_path_buf(),
			source: Box::new(source),
		}
	})
}

fn strip_dart_capacity_marker_artifacts(
	generated: &Path,
	capacity_index: &CompactCapacityIndex,
) -> Result<(), CodamaError> {
	let marker_stems = capacity_index
		.marker_names()
		.iter()
		.map(|marker| marker.to_snake_case())
		.collect::<Vec<_>>();
	for entry in WalkDir::new(generated).min_depth(1).max_depth(3) {
		let entry = entry.map_err(|source| {
			CodamaError::DartClient {
				path: generated.to_path_buf(),
				source: Box::new(std::io::Error::other(source)),
			}
		})?;
		let path = entry.path();
		if !path.is_file() || path.extension().is_none_or(|extension| extension != "dart") {
			continue;
		}
		let stem = path
			.file_stem()
			.and_then(|stem| stem.to_str())
			.unwrap_or_default();
		if marker_stems.iter().any(|marker| marker == stem) {
			std::fs::remove_file(path).map_err(|source| {
				CodamaError::DartClient {
					path: path.to_path_buf(),
					source: Box::new(source),
				}
			})?;
			continue;
		}
		if !stem.ends_with('s') && stem != "types" {
			continue;
		}
		let source = std::fs::read_to_string(path).map_err(|source| {
			CodamaError::DartClient {
				path: path.to_path_buf(),
				source: Box::new(source),
			}
		})?;
		let filtered = source
			.lines()
			.filter(|line| !marker_stems.iter().any(|marker| line.contains(marker)))
			.collect::<Vec<_>>()
			.join("\n")
			+ "\n";
		std::fs::write(path, filtered).map_err(|source| {
			CodamaError::DartClient {
				path: path.to_path_buf(),
				source: Box::new(source),
			}
		})?;
	}
	Ok(())
}

fn harden_dart_codec_source(
	source: &str,
	field_capacities: &[(String, CompactCapacity)],
	fixed_layouts: &[(String, DartFixedLayout)],
) -> String {
	let mut hardened = source.to_owned();
	for (field, metadata) in field_capacities {
		let (encoder_call, decoder_call, encoder_wrapper, decoder_wrapper) = match metadata.kind {
			CompactCapacityKind::Vec => {
				(
					"getArrayEncoder(",
					"getArrayDecoder(",
					"getPinaPodBoundedArrayEncoder",
					"getPinaPodBoundedArrayDecoder",
				)
			}
			CompactCapacityKind::String => {
				(
					"addEncoderSizePrefix(",
					"addDecoderSizePrefix(",
					"getPinaPodBoundedStringEncoder",
					"getPinaPodBoundedStringDecoder",
				)
			}
		};
		hardened = harden_dart_collection_call(
			&hardened,
			field,
			encoder_call,
			encoder_wrapper,
			metadata.capacity,
			false,
		);
		hardened = harden_dart_collection_call(
			&hardened,
			field,
			decoder_call,
			decoder_wrapper,
			metadata.capacity,
			true,
		);
		if let Some(offset) = metadata.option_tag_offset {
			hardened = harden_dart_dynamic_option_prefix_call(
				&hardened,
				field,
				"getNullableEncoder",
				&format!(
					"offsetEncoder(offsetEncoder(getU8Encoder(), OffsetConfig(preOffset: (scope) \
					 => {offset})), OffsetConfig(postOffset: (scope) => scope.preOffset))"
				),
			);
			hardened = harden_dart_dynamic_option_prefix_call(
				&hardened,
				field,
				"getNullableDecoder",
				&format!(
					"offsetDecoder(offsetDecoder(getU8Decoder(), OffsetConfig(preOffset: (scope) \
					 => {offset})), OffsetConfig(postOffset: (scope) => scope.preOffset))"
				),
			);
		}
	}
	for (field, layout) in fixed_layouts {
		hardened = harden_dart_fixed_bytes_call(
			&hardened,
			field,
			"fixEncoderSize(getBytesEncoder()",
			"getPinaPodFixedBytesEncoder",
			layout,
		);
		hardened = harden_dart_fixed_bytes_call(
			&hardened,
			field,
			"fixDecoderSize(getBytesDecoder()",
			"getPinaPodFixedBytesDecoder",
			layout,
		);
	}

	if hardened == source || hardened.contains("../pina_pod_codecs.dart") {
		return hardened;
	}
	let import = "import '../pina_pod_codecs.dart';\n";
	if let Some(offset) = hardened.find("import '") {
		hardened.insert_str(offset, import);
	}
	hardened
}

fn harden_dart_dynamic_option_prefix_call(
	source: &str,
	field: &str,
	call_marker: &str,
	prefix: &str,
) -> String {
	let field_marker = format!("'{field}',");
	let Some(call_start) = dart_field_scoped_call_start(source, &field_marker, call_marker) else {
		return source.to_owned();
	};
	let Some(relative_end) = dart_matching_call_end(&source[call_start..]) else {
		return source.to_owned();
	};
	let call_end = call_start + relative_end;
	let call = &source[call_start..=call_end];
	if call.contains("prefix:") && call.contains("preOffset") {
		return source.to_owned();
	}

	let mut output = source.to_owned();
	output.insert_str(call_end, &format!(", prefix: {prefix}"));
	output
}

fn harden_dart_fixed_bytes_call(
	source: &str,
	field: &str,
	call_marker: &str,
	wrapper: &str,
	layout: &DartFixedLayout,
) -> String {
	let field_marker = format!("'{field}',");
	let Some(call_start) = dart_field_scoped_call_start(source, &field_marker, call_marker) else {
		return source.to_owned();
	};
	let Some(call_end) = dart_matching_call_end(&source[call_start..]) else {
		return source.to_owned();
	};
	let call_end = call_start + call_end;
	if source[..call_start]
		.trim_end()
		.ends_with(&format!("{wrapper}("))
	{
		return source.to_owned();
	}
	let call = &source[call_start..=call_end];
	let replacement = format!("{wrapper}({call}, {})", layout.render());
	let mut output = source.to_owned();
	output.replace_range(call_start..=call_end, &replacement);
	output
}

fn harden_dart_collection_call(
	source: &str,
	field: &str,
	call_marker: &str,
	wrapper: &str,
	capacity: usize,
	harden_prefix: bool,
) -> String {
	let field_marker = format!("'{field}',");
	let Some(call_start) = dart_field_scoped_call_start(source, &field_marker, call_marker) else {
		return source.to_owned();
	};
	let Some(call_end) = dart_matching_call_end(&source[call_start..]) else {
		return source.to_owned();
	};
	let call_end = call_start + call_end;
	if source[..call_start]
		.trim_end()
		.ends_with(&format!("{wrapper}("))
	{
		return source.to_owned();
	}
	let mut call = source[call_start..=call_end].to_owned();
	let mut count_decoder = None;
	if harden_prefix {
		if call_marker == "getArrayDecoder(" {
			count_decoder = dart_array_count_decoder(&call)
				.map(|decoder| format!("getPinaPodBoundedCountDecoder({decoder}, {capacity})"));
		} else {
			call = harden_dart_prefix_decoder(&call, capacity);
		}
	}
	let replacement = count_decoder.map_or_else(
		|| format!("{wrapper}({call}, {capacity})"),
		|count_decoder| format!("{wrapper}({call}, {count_decoder}, {capacity})"),
	);
	let mut output = source.to_owned();
	output.replace_range(call_start..=call_end, &replacement);
	output
}

fn dart_array_count_decoder(call: &str) -> Option<&str> {
	let marker = "PrefixedArraySize(";
	let start = call.find(marker)?;
	let expression_start = start + marker.len();
	let end = dart_matching_call_end(&call[start..])?;
	let expression_end = start + end;

	Some(&call[expression_start..expression_end])
}

fn dart_field_scoped_call_start(
	source: &str,
	field_marker: &str,
	call_marker: &str,
) -> Option<usize> {
	let mut search_offset = 0usize;
	while let Some(field_offset) = source[search_offset..].find(field_marker) {
		let field_start = search_offset + field_offset;
		let scope_start = field_start + field_marker.len();
		let tuple_start = source[..field_start]
			.char_indices()
			.rev()
			.find(|(_, character)| !character.is_whitespace())
			.and_then(|(index, character)| (character == '(').then_some(index));
		let scope_end = tuple_start
			.and_then(|start| dart_matching_delimiter_end(&source[start..], '(', ')'))
			.map_or(scope_start, |end| tuple_start.unwrap_or_default() + end);
		if let Some(call_offset) = source[scope_start..scope_end].find(call_marker) {
			return Some(scope_start + call_offset);
		}
		search_offset = scope_start;
	}
	None
}

fn dart_matching_delimiter_end(source: &str, open: char, close: char) -> Option<usize> {
	let mut depth = 0usize;
	let mut quote = None;
	let mut escaped = false;
	for (index, character) in source.char_indices() {
		if let Some(active_quote) = quote {
			if escaped {
				escaped = false;
				continue;
			}
			if character == '\\' {
				escaped = true;
				continue;
			}
			if character == active_quote {
				quote = None;
			}
			continue;
		}

		match character {
			'\'' | '"' => quote = Some(character),
			character if character == open => depth = depth.checked_add(1)?,
			character if character == close => {
				depth = depth.checked_sub(1)?;
				if depth == 0 {
					return Some(index);
				}
			}
			_ => {}
		}
	}
	None
}

fn harden_dart_prefix_decoder(call: &str, capacity: usize) -> String {
	let marker = "PrefixedArraySize(";
	if let Some(start) = call.find(marker) {
		let expression_start = start + marker.len();
		let Some(end) = dart_matching_call_end(&call[start..]) else {
			return call.to_owned();
		};
		let expression_end = start + end;
		let expression = &call[expression_start..expression_end];
		if expression
			.trim_start()
			.starts_with("getPinaPodBoundedCountDecoder(")
		{
			return call.to_owned();
		}
		let replacement = format!("getPinaPodBoundedCountDecoder({expression}, {capacity})");
		let mut output = call.to_owned();
		output.replace_range(expression_start..expression_end, &replacement);
		return output;
	}

	let Some(open) = call.find('(') else {
		return call.to_owned();
	};
	let Some(comma) = dart_top_level_comma(&call[open + 1..]).map(|comma| open + 1 + comma) else {
		return call.to_owned();
	};
	let expression_start = comma
		+ 1 + call[comma + 1..]
		.len()
		.saturating_sub(call[comma + 1..].trim_start().len());
	let expression_end = call.len().saturating_sub(1);
	let expression = &call[expression_start..expression_end];
	if expression
		.trim_start()
		.starts_with("getPinaPodBoundedCountDecoder(")
	{
		return call.to_owned();
	}
	let replacement = format!("getPinaPodBoundedCountDecoder({expression}, {capacity})");
	let mut output = call.to_owned();
	output.replace_range(expression_start..expression_end, &replacement);
	output
}

fn dart_matching_call_end(call: &str) -> Option<usize> {
	let mut depth = 0usize;
	for (index, character) in call.char_indices() {
		match character {
			'(' => depth = depth.checked_add(1)?,
			')' => {
				depth = depth.checked_sub(1)?;
				if depth == 0 {
					return Some(index);
				}
			}
			_ => {}
		}
	}
	None
}

fn dart_top_level_comma(source: &str) -> Option<usize> {
	let mut depth = 0usize;
	for (index, character) in source.char_indices() {
		match character {
			'(' | '[' | '{' => depth = depth.checked_add(1)?,
			')' | ']' | '}' => depth = depth.checked_sub(1)?,
			',' if depth == 0 => return Some(index),
			_ => {}
		}
	}
	None
}

/// Writes deterministic package-root entrypoints for rendered Dart programs.
pub fn write_dart_package_barrels(
	output_root: &Path,
	programs: &[String],
) -> Result<(), CodamaError> {
	let mut programs = programs.to_vec();
	programs.sort();

	for program in programs {
		let source = format!(
			"// Auto-generated by `pina codama generate`. Do not edit.\n\nexport \
			 'src/generated/{program}/{program}.dart';\n",
		);
		let path = output_root.join("lib").join(format!("{program}.dart"));
		std::fs::write(&path, source).map_err(|source| {
			CodamaError::DartClient {
				path,
				source: Box::new(source),
			}
		})?;
	}

	Ok(())
}

fn validate_supported_types(value: &Value, path: &Path) -> Result<(), CodamaError> {
	match value {
		Value::Array(values) => {
			for value in values {
				validate_supported_types(value, path)?;
			}
		}
		Value::Object(object) => {
			let kind = object.get("kind").and_then(Value::as_str);

			if let Some(kind) = kind
				&& kind.ends_with("TypeNode")
				&& !matches!(
					kind,
					"arrayTypeNode"
						| "booleanTypeNode"
						| "bytesTypeNode" | "definedTypeLinkNode"
						| "definedTypeNode"
						| "enumEmptyVariantTypeNode"
						| "enumTypeNode" | "fixedSizeTypeNode"
						| "numberTypeNode" | "optionTypeNode"
						| "postOffsetTypeNode"
						| "preOffsetTypeNode"
						| "publicKeyTypeNode"
						| "sizePrefixTypeNode"
						| "stringTypeNode" | "structFieldTypeNode"
						| "structTypeNode"
				) {
				return Err(dart_error(
					path,
					format!("Dart renderer does not support semantic type `{kind}`"),
				));
			}

			match kind {
				Some("stringTypeNode") => {
					if object.get("encoding").and_then(Value::as_str) != Some("utf8") {
						return Err(dart_error(
							path,
							"Dart PinaPod strings require UTF-8 encoding".to_owned(),
						));
					}
				}
				Some("numberTypeNode") => validate_number_type(object, path)?,
				Some("optionTypeNode") => validate_option_type(object, path)?,
				_ => {}
			}

			for value in object.values() {
				validate_supported_types(value, path)?;
			}
		}
		_ => {}
	}

	Ok(())
}

fn validate_number_type(
	object: &serde_json::Map<String, Value>,
	path: &Path,
) -> Result<(), CodamaError> {
	let format = object.get("format").and_then(Value::as_str);
	if !matches!(
		format,
		Some(
			"u8" | "u16"
				| "u32" | "u64"
				| "u128" | "i8"
				| "i16" | "i32"
				| "i64" | "i128"
				| "f32" | "f64"
		)
	) {
		return Err(dart_error(
			path,
			format!(
				"Dart renderer does not support number format `{}`",
				format.unwrap_or("<missing>"),
			),
		));
	}

	if object.get("endian").and_then(Value::as_str) != Some("le") {
		return Err(dart_error(
			path,
			"Pina PinaPod numbers require little-endian encoding".to_owned(),
		));
	}

	Ok(())
}

fn validate_option_type(
	object: &serde_json::Map<String, Value>,
	path: &Path,
) -> Result<(), CodamaError> {
	let fixed = object.get("fixed").and_then(Value::as_bool) == Some(true);
	if !fixed {
		let item = object
			.get("item")
			.ok_or_else(|| dart_error(path, "compact Option is missing its item".to_owned()))?;
		if !is_dynamic_collection_value(item) {
			return Err(dart_error(
				path,
				"variable PinaPod options must contain a compact String or Vec".to_owned(),
			));
		}
	}

	let prefix = object
		.get("prefix")
		.and_then(nested_number_format)
		.ok_or_else(|| {
			dart_error(
				path,
				"PinaPod Option is missing its numeric prefix".to_owned(),
			)
		})?;
	if (!fixed && prefix != "u8") || (fixed && !matches!(prefix, "u8" | "u16" | "u32")) {
		return Err(dart_error(
			path,
			format!("PinaPod Option does not support prefix format `{prefix}`"),
		));
	}
	Ok(())
}

fn nested_number_format(value: &Value) -> Option<&str> {
	let object = value.as_object()?;
	match object.get("kind").and_then(Value::as_str)? {
		"numberTypeNode" => object.get("format").and_then(Value::as_str),
		"preOffsetTypeNode" | "postOffsetTypeNode" => {
			object.get("type").and_then(nested_number_format)
		}
		_ => None,
	}
}

fn is_dynamic_collection_value(value: &Value) -> bool {
	let Some(object) = value.as_object() else {
		return false;
	};
	match object.get("kind").and_then(Value::as_str) {
		Some("arrayTypeNode") => {
			object
				.get("count")
				.and_then(Value::as_object)
				.and_then(|count| count.get("kind"))
				.and_then(Value::as_str)
				== Some("prefixedCountNode")
		}
		Some("sizePrefixTypeNode") => {
			object
				.get("type")
				.and_then(Value::as_object)
				.and_then(|inner| inner.get("kind"))
				.and_then(Value::as_str)
				== Some("stringTypeNode")
		}
		Some("preOffsetTypeNode" | "postOffsetTypeNode") => {
			object.get("type").is_some_and(is_dynamic_collection_value)
		}
		_ => false,
	}
}

fn dart_error(path: impl AsRef<Path>, message: String) -> CodamaError {
	CodamaError::DartClientValidation {
		path: path.as_ref().to_path_buf(),
		message,
	}
}

