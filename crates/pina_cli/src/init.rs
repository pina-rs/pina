fn cargo_config_template(sbpf_linker: bool) -> String {
	if sbpf_linker {
		return r#"[alias]
# Experimental upstream sbpf-linker build. LTO is deliberately absent: fat LTO
# under sbpf-linker inflates runtime compute units. See
# docs/sbpf-linker-evaluation.md for the measured caveats.
build-program = "build --release --target bpfel-unknown-none -Z build-std=core,alloc -F bpf-entrypoint"

[target.bpfel-unknown-none]
# Static syscalls are load-bearing: without the two --cfg flags the pinocchio
# syscall externs fall back to relocation-based resolution that sbpf-linker
# mishandles, producing programs that load but silently corrupt data.
rustflags = [
	"-C", "linker=sbpf-linker",
	"-C", "panic=abort",
	"-C", "relocation-model=static",
	"-C", "target-cpu=v4",
	"-C", "target-feature=+allows-misaligned-mem-access",
	"-C", "link-arg=--llvm-args=--bpf-stack-size=4096",
	"-C", "link-arg=--llvm-args=--bpf-max-stores-per-memfunc=5",
	"-C", "link-arg=--llvm-args=--disable-gotox",
	"-C", "link-arg=--llvm-args=--disable-ldsx",
	"-C", "link-arg=--llvm-args=--disable-movsx",
	"--cfg=target_os=\"solana\"",
	"--cfg=target_feature=\"static-syscalls\"",
	"-A", "explicit_builtin_cfgs_in_flags",
]
"#
		.to_owned();
	}
	"[alias]\nbuild-program = \"build-sbf --sbf-out-dir target/deploy -F bpf-entrypoint\"\n"
		.to_owned()
}

fn lib_template(package_name: &str, program_title: &str) -> String {
	format!(
		r#"//! {program_title} — starter Pina program generated by `pina init`.

#![allow(clippy::inline_always)]
#![no_std]

#[cfg(all(
	not(target_arch = "bpf"),
	not(feature = "bpf-entrypoint"),
	not(test)
))]
extern crate std;

#[cfg(feature = "bpf-entrypoint")]
pub mod entrypoint;

use pina::*;

// Replace this with your deployed program address before sharing the project.
declare_id!("{PLACEHOLDER_PROGRAM_ID}");

#[discriminator]
pub enum {program_title}Instruction {{
	Initialize = 0,
}}

#[instruction(discriminator = {program_title}Instruction::Initialize)]
pub struct InitializeInstruction {{
	pub value: u8,
}}

#[derive(Accounts, Debug)]
pub struct InitializeAccounts<'a> {{
	pub authority: &'a AccountView,
}}

impl<'a> ProcessAccountInfos<'a> for InitializeAccounts<'a> {{
	fn process(self, data: &[u8]) -> ProgramResult {{
		let args = InitializeInstruction::try_from_bytes(data)?;
		self.authority.assert_signer()?;
		if args.value == 0 {{
			return Err(ProgramError::InvalidArgument);
		}}

		log!("Initialized {package_name}");
		Ok(())
	}}
}}

// Unit tests live here, next to the code they cover, so `cargo test --lib`
// measures the real program source. The crate is `cdylib` only for LTO, and
// Cargo still builds this test harness from `src/lib.rs`.
#[cfg(test)]
mod tests {{
	use super::*;

	/// The instruction discriminator is part of the wire format. Treat a
	/// change here as a breaking change for deployed clients.
	#[test]
	fn instruction_discriminator_is_stable() {{
		assert_eq!({program_title}Instruction::Initialize as u8, 0);
	}}

	#[test]
	fn decodes_initialized_instruction() {{
		let mut data = [0u8; InitializeInstruction::SIZE];
		InitializeInstruction::initialize(&mut data, |args| {{
			args.value = 7;
			Ok(())
		}})
		.expect("initialize instruction storage");

		let decoded = InitializeInstruction::try_from_bytes(&data)
			.expect("decode initialized instruction");
		assert_eq!(decoded.value, 7);
	}}

	#[test]
	fn rejects_wrong_program_id() {{
		let wrong_id: Address = [9u8; 32].into();
		let data = [{program_title}Instruction::Initialize as u8];
		let result = parse_instruction::<{program_title}Instruction>(&wrong_id, &ID, &data);

		assert!(matches!(result, Err(ProgramError::IncorrectProgramId)));
	}}
}}

pub fn process_instruction(
	program_id: &Address,
	accounts: &mut [AccountView],
	data: &[u8],
) -> ProgramResult {{
	let instruction: {program_title}Instruction = parse_instruction(program_id, &ID, data)?;
	match instruction {{
		{program_title}Instruction::Initialize => {{
			InitializeAccounts::try_from((program_id, accounts))?.process(data)
		}}
	}}
}}
"#
	)
}

