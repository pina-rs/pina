/// Errors produced during project initialization.
#[derive(Debug, thiserror::Error)]
pub enum InitError {
	#[error(
		"invalid package name `{name}`: use 1-64 ASCII letters, digits, `_`, or `-`, start with a \
		 letter or `_`, and avoid Rust keywords, because the name becomes the crate name of the \
		 program and of every generated client"
	)]
	InvalidPackageName { name: String },

	#[error("refusing to overwrite existing file: {path}")]
	DestinationExists { path: PathBuf },

	#[error("IO error at {path}: {source}")]
	Io {
		path: PathBuf,
		source: std::io::Error,
	},
}

/// All scaffold files generated by `pina init`, expressed as relative paths.
const SCAFFOLD_FILES: &[&str] = &[
	"Cargo.toml",
	"pina.toml",
	"README.md",
	".gitignore",
	".cargo/config.toml",
	"build.rs",
	"src/lib.rs",
	"src/entrypoint.rs",
	"tests/integration.rs",
	"rust-toolchain.toml",
	"tests/surfpool/Cargo.toml",
	"tests/surfpool/src/lib.rs",
];

/// Options that vary how `pina init` scaffolds a project.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct InitOptions {
	/// Replace existing regular scaffold files; symbolic links and reparse points are rejected.
	pub force: bool,
	/// Scaffold for the experimental upstream sbpf-linker toolchain.
	pub sbpf_linker: bool,
}

/// Initialize a new Pina program project in `project_dir`.
///
/// When `force` is `false`, this function fails if any scaffold file already
/// exists. When `true`, regular scaffold entries are replaced, preserving other
/// hard links to the original files. Symbolic links, reparse points, and
/// non-regular destinations are rejected in either mode.
pub fn init_project(project_dir: &Path, package_name: &str, force: bool) -> Result<(), InitError> {
	init_project_with_options(
		project_dir,
		package_name,
		&InitOptions {
			force,
			sbpf_linker: false,
		},
	)
}

/// Initialize a new Pina program project with scaffold options.
///
/// # Errors
///
/// Returns an error for invalid names, linked or non-regular destinations,
/// existing files without `force`, or IO failures.
pub fn init_project_with_options(
	project_dir: &Path,
	package_name: &str,
	options: &InitOptions,
) -> Result<(), InitError> {
	if !is_valid_package_name(package_name) {
		return Err(InitError::InvalidPackageName {
			name: package_name.to_owned(),
		});
	}

	// Preflight every path before writing anything, including dangling links.
	for relative in SCAFFOLD_FILES {
		let path = project_dir.join(relative);

		if init_io(
			&path,
			crate::path_security::has_untrusted_link_component(&path),
		)? {
			return Err(unsafe_scaffold_path(path));
		}

		match fs::symlink_metadata(&path) {
			Ok(metadata) if !metadata.is_file() => {
				return Err(unsafe_scaffold_path(path));
			}
			Ok(_) if !options.force => {
				return Err(InitError::DestinationExists { path });
			}
			Ok(_) => {}
			Err(source) if source.kind() == std::io::ErrorKind::NotFound => {}
			Err(source) => return init_io(&path, Err(source)),
		}
	}

	let project = open_project_directory(project_dir)?;

	// Capability-relative creation cannot escape if an ancestor is replaced after preflight.
	for relative in ["src", "tests/surfpool/src", ".cargo"] {
		open_scaffold_directory(&project, project_dir, relative)?;
	}

	let program_title = package_name.replace(['-', '_'], " ").to_upper_camel_case();
	let write = |index: usize, contents: &str| {
		write_file(
			&project,
			project_dir,
			SCAFFOLD_FILES[index],
			contents,
			options.force,
		)
	};

	write(0, &cargo_toml_template(package_name))?;
	write(1, &pina_toml_template(options.sbpf_linker))?;
	write(2, &readme_template(package_name, options.sbpf_linker))?;
	write(3, &gitignore_template())?;
	write(4, &cargo_config_template(options.sbpf_linker))?;
	write(5, &build_script_template())?;
	write(6, &lib_template(package_name, &program_title))?;
	write(7, &entrypoint_template())?;
	write(8, &integration_test_template(package_name, &program_title))?;
	write(9, &rust_toolchain_template())?;
	write(10, &surfpool_cargo_toml_template(package_name))?;
	write(11, &surfpool_test_template())?;

	Ok(())
}

/// Print next-steps guidance to stdout.
pub fn print_next_steps(project_dir: &Path, package_name: &str) {
	print_next_steps_with_options(
		project_dir,
		package_name,
		&InitOptions {
			force: false,
			sbpf_linker: false,
		},
	);
}

/// Print next-steps guidance for the options the project was initialized with.
pub fn print_next_steps_with_options(
	project_dir: &Path,
	_package_name: &str,
	options: &InitOptions,
) {
	println!();
	println!("  Next steps:");
	println!();
	println!("    cd {}", project_dir.display());
	println!("    # 1. Give the program its own identity, then snapshot the ABI:");
	println!(
		"    pina keys new                  # write target/deploy/<name>-keypair.json and \
		 declare_id!"
	);
	println!("    pina migrations create --auto true  # track every contract; record version 0");
	println!();
	println!("    pina lint                      # run Pina's security lints");
	if options.sbpf_linker {
		println!(
			"    pina build                     # build SBF with the upstream sbpf-linker (pina.toml: \
			 sbpf-linker = true) and generate the IDL"
		);
	} else {
		println!("    pina build                     # build SBF and generate the IDL");
	}
	println!("    pina test --unit               # fast native tests");
	println!("    pina test                      # build SBF and test with Surfpool");
	println!("    pina dev --yes                 # create and review the Surfpool runbook");
	println!("    pina generate                  # generate configured clients");
	println!();
	println!(
		"  Run `pina migrations create` only after the declared program address is final: the \
		 recorded history is bound to that address. Versions are counted per contract, so the \
		 default `u8` width gives each one 255 versions; add `--version-type u16` (or `u32`) to \
		 that first run only if one contract may need more, because the width freezes at the \
		 first deployment."
	);
	println!(
		"  The program keypair lives under the git-ignored `target/deploy/`, so `cargo clean` \
		 deletes it. Back it up before deploying; it is the program's upgrade identity."
	);
	if let Some(workspace) = enclosing_workspace(project_dir) {
		println!(
			"  This program is inside the workspace at {}. Add it to that workspace's `members`, \
			 and add the dependencies generated Rust clients inherit to its \
			 `[workspace.dependencies]`.",
			workspace.display()
		);
	}
	println!();
}

