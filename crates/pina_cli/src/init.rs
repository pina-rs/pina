/// Build script that keeps macro expansion fresh when the migration policy or
/// manifest changes.
///
/// A proc macro does not re-expand when the manifest changes, so the recorded
/// `auto` policy needs this directive to take effect on the next build. `pina
/// migrations create` scaffolds the same file when it is missing, and the
/// crate-level doc comment keeps the script warning-clean in projects that lint
/// with `-D warnings`.
fn build_script_template() -> String {
	"//! Re-expand Pina macros when the migration manifest changes.\n\nfn main() \
	 {\n\tprintln!(\"cargo:rerun-if-changed=migrations/manifest.json\");\n}\n"
		.to_owned()
}

/// Rust keywords that cannot name a crate, so they cannot name a program whose
/// generated clients declare modules and crates after it.
const RUST_KEYWORDS: &[&str] = &[
	"abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "crate",
	"do", "dyn", "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl",
	"in", "let", "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref",
	"return", "self", "static", "struct", "super", "trait", "true", "try", "type", "typeof",
	"unsafe", "unsized", "use", "virtual", "where", "while", "yield",
];

/// Longest accepted package name, well inside Cargo's and file systems' limits.
const MAX_PACKAGE_NAME_LEN: usize = 64;

fn is_valid_package_name(name: &str) -> bool {
	let Some(first) = name.chars().next() else {
		return false;
	};
	if name.len() > MAX_PACKAGE_NAME_LEN || !(first.is_ascii_alphabetic() || first == '_') {
		return false;
	}
	if !name
		.chars()
		.all(|ch| ch.is_ascii_alphanumeric() || ch == '-' || ch == '_')
	{
		return false;
	}

	let identifier = name.replace('-', "_").to_ascii_lowercase();
	identifier != "_" && !RUST_KEYWORDS.contains(&identifier.as_str())
}

/// The manifest of the Cargo workspace enclosing `project_dir`, if any.
///
/// A program scaffolded inside a workspace must be listed in that workspace's
/// members before Cargo will build it, so `pina init` points at it.
fn enclosing_workspace(project_dir: &Path) -> Option<PathBuf> {
	// The destination may not exist yet; its nearest existing ancestor can
	// then be the workspace root itself, so only an existing destination skips
	// its own manifest.
	let start = project_dir
		.ancestors()
		.find_map(|candidate| fs::canonicalize(candidate).ok())?;
	let own = usize::from(project_dir.exists());
	start.ancestors().skip(own).find_map(|directory| {
		let manifest = directory.join("Cargo.toml");
		let contents = fs::read_to_string(&manifest).ok()?;
		let table = contents.parse::<toml::Table>().ok()?;
		table.contains_key("workspace").then_some(manifest)
	})
}

/// Pin each component without following links, including newly created directories.
/// The caller must preflight the path first, which permits only trusted system aliases.
fn open_project_directory(path: &Path) -> Result<Dir, InitError> {
	let absolute = init_io(path, std::path::absolute(path))?;
	let root = absolute.ancestors().last().unwrap_or(&absolute);
	let mut directory = init_io(root, Dir::open_ambient_dir(root, ambient_authority()))?;
	let mut current = root.to_path_buf();

	for component in absolute.components() {
		match component {
			Component::RootDir | Component::Prefix(_) | Component::CurDir => {}
			Component::ParentDir => {
				directory = init_io(&current, directory.open_parent_dir(ambient_authority()))?;
				current.pop();
			}
			Component::Normal(name) => {
				let top_level = current == root;
				current.push(name);

				// Unix preflight permits only root-owned system aliases here (/tmp, /var).
				// Their replacement is outside the untrusted project tree's authority.
				if top_level
					&& fs::symlink_metadata(&current)
						.is_ok_and(|metadata| crate::path_security::is_link_like(&metadata))
				{
					let resolved = resolve_system_alias(&current)?;
					directory = init_io(
						&current,
						Dir::open_ambient_dir(&resolved, ambient_authority()),
					)?;
					current = resolved;
					continue;
				}

				match directory.create_dir(name) {
					Ok(()) => {}
					Err(source) if source.kind() == std::io::ErrorKind::AlreadyExists => {}
					Err(source) => return init_io(&current, Err(source)),
				}

				directory = init_io(&current, directory.open_dir_nofollow(name))?;
			}
		}
	}

	Ok(directory)
}

/// Resolve a link-like root component only where preflight permits trusted aliases.
fn resolve_system_alias(path: &Path) -> Result<PathBuf, InitError> {
	#[cfg(windows)]
	{
		Err(unsafe_scaffold_path(path.to_path_buf()))
	}

	#[cfg(not(windows))]
	{
		init_io(path, fs::canonicalize(path))
	}
}

/// Pin every scaffold parent so links cannot be followed between validation and creation.
fn open_scaffold_directory(project: &Dir, root: &Path, relative: &str) -> Result<Dir, InitError> {
	let mut directory = init_io(root, project.try_clone())?;
	let mut path = root.to_path_buf();

	for component in Path::new(relative) {
		path.push(component);

		match directory.create_dir(component) {
			Ok(()) => {}
			Err(source) if source.kind() == std::io::ErrorKind::AlreadyExists => {}
			Err(source) => return init_io(&path, Err(source)),
		}

		directory = init_io(&path, directory.open_dir_nofollow(component))?;
	}

	Ok(directory)
}

/// Replace directory entries without ever opening an existing scaffold file for writing.
fn write_file(
	project: &Dir,
	root: &Path,
	relative: &str,
	contents: &str,
	force: bool,
) -> Result<(), InitError> {
	let path = root.join(relative);
	let (parent, name) = relative.rsplit_once('/').unwrap_or(("", relative));
	let directory = open_scaffold_directory(project, root, parent)?;

	if force {
		match directory.symlink_metadata(name) {
			Ok(metadata) => {
				if !metadata.is_file() {
					return Err(unsafe_scaffold_path(path));
				}

				#[cfg(windows)]
				{
					use cap_std::fs::MetadataExt as _;

					const FILE_ATTRIBUTE_REPARSE_POINT: u32 = 0x400;

					if metadata.file_attributes() & FILE_ATTRIBUTE_REPARSE_POINT != 0 {
						return Err(unsafe_scaffold_path(path));
					}
				}

				// Unlinking never follows a swapped leaf or modifies its shared inode.
				init_io(&path, directory.remove_file(name))?;
			}
			Err(source) if source.kind() == std::io::ErrorKind::NotFound => {}
			Err(source) => return init_io(&path, Err(source)),
		}
	}

	let mut options = OpenOptions::new();
	options
		.write(true)
		.create_new(true)
		.follow(FollowSymlinks::No);
	let mut file = init_io(&path, directory.open_with(name, &options))?;

	init_io(&path, file.write_all(contents.as_bytes()))
}

fn init_io<T>(path: &Path, result: std::io::Result<T>) -> Result<T, InitError> {
	result.map_err(|source| {
		InitError::Io {
			path: path.to_path_buf(),
			source,
		}
	})
}

fn unsafe_scaffold_path(path: PathBuf) -> InitError {
	InitError::Io {
		path,
		source: std::io::Error::new(
			std::io::ErrorKind::InvalidInput,
			"refusing unsafe scaffold path; expected ordinary directories and regular files",
		),
	}
}

fn cargo_toml_template(package_name: &str) -> String {
	let pina_version = env!("CARGO_PKG_VERSION");

	// Package metadata rather than `[workspace.metadata]`: any `[workspace]`
	// table makes the program a workspace root, which breaks an enclosing
	// workspace that lists it as a member ("multiple workspace roots").
	format!(
		r#"[package]
name = "{package_name}"
version = "0.1.0"
edition = "2024"
publish = false

[package.metadata.cli]
solana = "3.0.0"

[lib]
# `cdylib` only. A second `lib`/`rlib` crate type makes rustc reject LTO for
# the program, which costs 20-35% of deployed program size. Integration tests
# exercise the real source with the `#[path = "../src/lib.rs"]` pattern in
# `tests/integration.rs` instead of linking this crate.
crate-type = ["cdylib"]

[features]
default = []
# Enables formatted failure diagnostics and caller locations. Costs `core::fmt`
# in the deployed binary; use it while debugging, not for production deploys.
verbose-logs = ["pina/verbose-logs"]
bpf-entrypoint = []

[dependencies]
# `account-resize` backs the reserved `Migrate` route that
# `#[discriminator(entrypoint)]` generates, which is how a scaffolded program
# serves migrations.
pina = {{ version = "{pina_version}", features = ["account-resize", "logs", "derive"] }}

# Production profile for the deployed program. Every setting here either
# shrinks the deployed binary or keeps the build honest about it.
#
# `overflow-checks` is opt-in: leaving it off turns arithmetic overflow from a
# panic into a wrap, which is cheaper but loses a real class of bug detection.
# Set it to `true` while the program is young even though it costs bytes.
[profile.release]
opt-level = 3
lto = "fat"
codegen-units = 1
panic = "abort"
strip = true
overflow-checks = false

# Build scripts and proc macros do not ship in the deployed program, so they
# should not be built at the program's opt-level or serialized behind its
# codegen-units setting.
[profile.release.build-override]
opt-level = 3
codegen-units = 1
incremental = false

[lints.rust.unexpected_cfgs]
level = "warn"
check-cfg = [
	'cfg(target_os, values("solana"))',
]
"#
	)
}

