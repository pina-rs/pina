/// Clear one initialized fixed representation after application validation fails.
///
/// This is public only so Pina's generated code can share the audited operation.
#[cfg(feature = "validation")]
#[doc(hidden)]
#[inline]
#[allow(unsafe_code)]
pub fn __clear_zc<T: crate::ZcElem>(value: &mut T) {
	// SAFETY: `value` is exclusively borrowed for its complete size. `ZcElem`
	// guarantees no padding, validity for every initialized bit pattern, and that
	// the all-zero representation is safe to inspect during initialization.
	unsafe { core::ptr::from_mut(value).write_bytes(0, 1) };
}

/// A native account schema with a PinaPod-generated zero-copy representation.
///
/// `Self` is the ergonomic Rust schema declared with [`crate::account`]. It is
/// never reinterpreted as account memory. `PinaPod` derives a separate
/// [`PinaPodFixed::Zc`] companion (for example, `CounterStateZc`) and owns the
/// validated conversion from account bytes to that representation.
///
/// Pina's audited account contract is the implementation generated by
/// [`crate::account`]. Manually implementing this trait is an advanced escape
/// hatch outside that closed contract. A manual implementation must ensure
/// that its [`PinaPodFixed`] implementation upholds `PinaPod`'s bit-validity,
/// alignment, initialization, size, validation-order, and aliasing invariants
/// for every possible input byte slice.
///
/// # Examples
///
/// ```ignore
/// use pina::PinaAccount;
///
/// // `MyAccount` is generated by `#[account]`; it implements `PinaAccount`.
/// let account = MyAccount::try_from_bytes(&data)
///     .unwrap_or_else(|e| panic!("deserialization failed: {e:?}"));
/// assert_eq!(account.value.get(), 42);
/// ```
pub trait PinaAccount: HasDiscriminator + PinaPodFixed {
	/// Write the framework-owned discriminator into the generated zero-copy
	/// representation.
	///
	/// The [`crate::account`] macro implements this hook. Manual implementations
	/// must write the discriminator field that occupies the leading bytes of
	/// `value`.
	#[doc(hidden)]
	fn write_zc_discriminator(value: &mut Self::Zc);

	/// Run application validation generated for this account schema.
	///
	/// Manual `PinaAccount` implementations inherit a no-op hook. The
	/// `#[account]` macro overrides it when the `validation` feature is enabled.
	#[cfg(feature = "validation")]
	#[doc(hidden)]
	fn validate_account_value(_value: &Self::Zc) -> ProgramResult {
		Ok(())
	}

	/// Initialize a complete fixed account representation in one validated pass.
	///
	/// `PinaPod` clears the destination before calling `initialize` and clears it
	/// again if the closure or structural validation fails. Pina writes the
	/// account discriminator before handing the generated zero-copy view to the
	/// caller, then runs application validation on the completed view and clears
	/// the destination if that validation fails.
	fn initialize<F>(data: &mut [u8], initialize: F) -> Result<&mut Self::Zc, ProgramError>
	where
		F: FnOnce(&mut Self::Zc) -> Result<(), crate::PinaPodError>,
	{
		#[cfg(not(feature = "validation"))]
		{
			<Self as PinaPodFixed>::initialize(data, |value| {
				Self::write_zc_discriminator(value);
				initialize(value)
			})
			.map_err(|_| ProgramError::InvalidAccountData)
		}

		#[cfg(feature = "validation")]
		{
			let value = <Self as PinaPodFixed>::initialize(data, |value| {
				Self::write_zc_discriminator(value);
				initialize(value)
			})
			.map_err(|_| ProgramError::InvalidAccountData)?;

			if let Err(error) = Self::validate_account_value(value) {
				__clear_zc(value);
				return Err(error);
			}

			Ok(value)
		}
	}

	/// Initialize a complete fixed account representation into an already-zeroed
	/// destination buffer.
	///
	/// The default forwards to [`Self::initialize`] so manual [`PinaAccount`]
	/// implementations that override `initialize` keep their custom behavior.
	/// `#[account]` overrides this via [`__initialize_derived_zeroed`] to skip
	/// the redundant `data.fill(0)` pass on freshly allocated accounts while
	/// preserving failure-clearing, discriminator-writing, structural, and
	/// application validation guarantees.
	#[doc(hidden)]
	fn __initialize_zeroed<F>(data: &mut [u8], initialize: F) -> Result<&mut Self::Zc, ProgramError>
	where
		F: FnOnce(&mut Self::Zc) -> Result<(), crate::PinaPodError>,
	{
		<Self as PinaAccount>::initialize(data, initialize)
	}

	/// Reject bytes whose migration version envelope is not current.
	///
	/// The default accepts every representation. The `#[account]` macro
	/// overrides this hook for `migrations`-aware schemas so every generic
	/// read path (`as_account`, `as_account_mut`, `validate_account_data`)
	/// refuses stale bytes instead of misreading them as the current layout.
	#[doc(hidden)]
	#[inline(always)]
	fn require_current_migration_envelope(_data: &[u8]) -> ProgramResult {
		Ok(())
	}

	/// Validate the discriminator and content of `data`.
	fn validate_account_data(data: &[u8]) -> Result<(), ProgramError> {
		if data.len() != size_of::<Self::Zc>() || !Self::matches_discriminator(data) {
			return Err(ProgramError::InvalidAccountData);
		}

		Self::require_current_migration_envelope(data)?;

		#[cfg(not(feature = "validation"))]
		{
			<Self as PinaPodFixed>::validate_exact(data)
				.map_err(|_| ProgramError::InvalidAccountData)
		}

		#[cfg(feature = "validation")]
		{
			let value = <Self as PinaPodFixed>::read_exact(data)
				.map_err(|_| ProgramError::InvalidAccountData)?;

			Self::validate_account_value(value)
		}
	}

	/// Validate `data`, then borrow `PinaPod`'s immutable zero-copy companion.
	fn try_from_bytes(data: &[u8]) -> Result<&Self::Zc, ProgramError> {
		if pinocchio::hint::unlikely(
			data.len() != size_of::<Self::Zc>() || !Self::matches_discriminator(data),
		) {
			return Err(ProgramError::InvalidAccountData);
		}

		Self::require_current_migration_envelope(data)?;

		#[cfg(not(feature = "validation"))]
		{
			<Self as PinaPodFixed>::read_exact(data).map_err(|_| ProgramError::InvalidAccountData)
		}

		#[cfg(feature = "validation")]
		{
			let value = <Self as PinaPodFixed>::read_exact(data)
				.map_err(|_| ProgramError::InvalidAccountData)?;
			Self::validate_account_value(value)?;

			Ok(value)
		}
	}

	/// Validate `data`, then borrow `PinaPod`'s mutable zero-copy companion.
	fn try_from_bytes_mut(data: &mut [u8]) -> Result<&mut Self::Zc, ProgramError> {
		if pinocchio::hint::unlikely(
			data.len() != size_of::<Self::Zc>() || !Self::matches_discriminator(data),
		) {
			return Err(ProgramError::InvalidAccountData);
		}

		Self::require_current_migration_envelope(data)?;

		#[cfg(not(feature = "validation"))]
		{
			<Self as PinaPodFixed>::read_exact_mut(data)
				.map_err(|_| ProgramError::InvalidAccountData)
		}

		#[cfg(feature = "validation")]
		{
			let value = <Self as PinaPodFixed>::read_exact_mut(data)
				.map_err(|_| ProgramError::InvalidAccountData)?;
			Self::validate_account_value(value)?;

			Ok(value)
		}
	}
}

/// Macro-generated zero-fill fast path for [`PinaAccount::__initialize_zeroed`].
///
/// Callers must guarantee that every byte of `data` is already zero (for
/// example, freshly allocated by the System Program).
#[doc(hidden)]
pub fn __initialize_derived_zeroed<T, F>(
	data: &mut [u8],
	initialize: F,
) -> Result<&mut T::Zc, ProgramError>
where
	T: PinaAccount,
	F: FnOnce(&mut T::Zc) -> Result<(), crate::PinaPodError>,
{
	#[cfg(not(feature = "validation"))]
	{
		<T as PinaPodFixed>::initialize_zeroed(data, |value| {
			T::write_zc_discriminator(value);
			initialize(value)
		})
		.map_err(|_| ProgramError::InvalidAccountData)
	}

	#[cfg(feature = "validation")]
	{
		let value = <T as PinaPodFixed>::initialize_zeroed(data, |value| {
			T::write_zc_discriminator(value);
			initialize(value)
		})
		.map_err(|_| ProgramError::InvalidAccountData)?;

		if let Err(error) = T::validate_account_value(value) {
			__clear_zc(value);
			return Err(error);
		}

		Ok(value)
	}
}

/// A discriminator-first, variable-length account schema.
///
/// Compact accounts keep inline fields and collection lengths in a fixed
/// header, followed by the active collection payloads in declaration order.
/// The associated immutable `Ref` and atomic `Patch` types are generated by
/// `#[account(compact)]`. A patch can calculate its resulting encoded length
/// through [`PinaCompactAccount::updated_len`] before it changes any bytes,
/// allowing [`crate::UpdateResizableAccount`] to grow before the update and
/// shrink afterward without exposing a mutable compact view.
#[cfg(feature = "compact")]
pub trait PinaCompactAccount: HasDiscriminator + PinaPodCompact {
	/// Immutable compact view generated by `PinaPod`.
	type Ref<'data>
	where
		Self: 'data;

	/// Borrowed, atomic update generated by `PinaPod`.
	type Patch<'patch>: crate::PinaPodPatch<Self>
	where
		Self: 'patch;

	/// Whether [`Self::validate_size`] is guaranteed to match
	/// [`PinaPodCompact::validate_storage_len`] (enforced prior to any mutation
	/// inside `pinapod`'s `try_update_or_len`).
	///
	/// `#[account(compact)]` sets this to `true` so [`crate::UpdateResizableAccount`]
	/// stays single-pass; manual implementations inherit `false` so any custom
	/// `validate_size` override runs before bytes are modified.
	#[doc(hidden)]
	const __DERIVED_COMPACT_VALIDATE_SIZE: bool = false;

	/// Validate that `size` can hold this compact account.
	fn validate_size(size: usize) -> Result<(), ProgramError> {
		<Self as PinaPodCompact>::validate_storage_len(size)
			.map_err(|_| ProgramError::InvalidAccountData)
	}

	/// Validate the discriminator, size bounds, header, and active tail.
	fn validate_account_data(data: &[u8]) -> Result<(), ProgramError> {
		Self::validate_size(data.len())?;

		if !Self::matches_discriminator(data) {
			return Err(ProgramError::InvalidAccountData);
		}

		<Self as PinaPodCompact>::validate(data).map_err(|_| ProgramError::InvalidAccountData)
	}

	/// Validate and borrow an immutable compact view.
	fn try_from_bytes(data: &[u8]) -> Result<Self::Ref<'_>, ProgramError>;

	/// Calculate the encoded length after applying `patch` without mutating `data`.
	fn updated_len(data: &[u8], patch: &Self::Patch<'_>) -> Result<usize, ProgramError>;

	/// Apply `patch` to initialized compact storage.
	///
	/// Structural patch failures leave `data` unchanged. With the `validation`
	/// feature, application validation runs on the completed in-place
	/// representation. Callers must propagate an application-validation error so
	/// the Solana runtime rolls the instruction back.
	fn update(data: &mut [u8], patch: &Self::Patch<'_>) -> Result<usize, ProgramError>;

	/// Initialize caller-owned compact storage from `patch`.
	fn initialize(data: &mut [u8], patch: &Self::Patch<'_>) -> Result<usize, ProgramError>;

	/// Apply `patch` in place when the encoded result fits in `data`, or return
	/// `Ok(Err(target_size))` without mutating `data` when the account must grow
	/// first.
	#[doc(hidden)]
	fn __try_update_or_len(
		data: &mut [u8],
		patch: &Self::Patch<'_>,
	) -> Result<Result<usize, usize>, ProgramError> {
		let target_size = Self::updated_len(data, patch)?;
		Self::validate_size(target_size)?;
		if target_size > data.len() {
			return Ok(Err(target_size));
		}

		let encoded_len = Self::update(data, patch)?;
		if encoded_len != target_size {
			return Err(ProgramError::InvalidAccountData);
		}

		Ok(Ok(encoded_len))
	}

	/// Initialize compact storage that is already guaranteed to be zero-filled.
	#[doc(hidden)]
	fn __initialize_zeroed(
		data: &mut [u8],
		patch: &Self::Patch<'_>,
	) -> Result<usize, ProgramError> {
		Self::initialize(data, patch)
	}
}

/// A patch value that exposes an account's exact generated compact patch type.
///
/// Compact account builders use this adapter instead of accepting any
/// [`crate::PinaPodPatch`] implementation. That keeps structural and
/// application validation on the generated [`PinaCompactAccount`] boundary.
/// Wrapper types may implement this trait by returning the generated patch
/// they contain; they cannot substitute a different patch representation.
#[cfg(feature = "compact")]
pub trait PinaCompactPatch<T: PinaCompactAccount> {
	/// Borrow the exact generated patch associated with `T`.
	fn as_pina_patch(&self) -> &T::Patch<'_>;
}

#[cfg(feature = "compact")]
impl<T, P> PinaCompactPatch<T> for &P
where
	T: PinaCompactAccount,
	P: PinaCompactPatch<T> + ?Sized,
{
	#[inline(always)]
	fn as_pina_patch(&self) -> &T::Patch<'_> {
		<P as PinaCompactPatch<T>>::as_pina_patch(*self)
	}
}

/// A compact account whose PDA bump seed is stored in a declared field.
///
/// `#[pda(bump = ...)]` on a `#[account(compact)]` struct generates the
/// implementation, which loads the declared field's byte directly from the
/// compact header. [`crate::CreateCompactProgramAccountWithBump`] requires it
/// so creation can reject a patch whose stored bump disagrees with the
/// canonical bump the builder validated: an account that stores a different
/// bump can never be loaded through the canonical stored-bump loaders, and the
/// surplus rent it holds is stranded until the account is closed.
#[cfg(feature = "compact")]
pub trait PinaCompactStoredBump: PinaCompactAccount {
	/// Load the stored bump field's byte from the compact header.
	///
	/// This is a direct offset read, not a validation pass: it returns
	/// [`ProgramError::InvalidAccountData`] only when `data` is too short to
	/// hold the header, and otherwise returns the byte at the field's offset
	/// without checking the discriminator or the tails.
	fn stored_bump(data: &[u8]) -> Result<u8, ProgramError>;
}

/// Validation trait for deserialized account data (e.g. `EscrowState`).
///
/// Allows chaining arbitrary boolean assertions on the typed account, returning
/// `Ok(&Self)` when the condition holds and `Err(InvalidAccountData)`
/// otherwise.
///
/// <!-- {=pinaValidationChainSnippet|trim|linePrefix:"/// ":true} -->
/// Validation methods are intentionally chainable: `account.assert_signer()?.assert_writable()?.assert_owner(&program_id)?`.<!-- {/pinaValidationChainSnippet} -->
/// <!-- {=pinaPublicResultContract|trim|linePrefix:"/// ":true} -->
/// All APIs in this section are designed for on-chain determinism.
///
/// They return `ProgramError` values for caller-side propagation with `?`.
///
/// No panics needed.<!-- {/pinaPublicResultContract} -->
///
/// # Examples
///
/// ```ignore
/// // Inside an instruction handler with a deserialized `escrow: &EscrowState`:
/// escrow.assert(|e| e.is_active.into())?;
/// escrow.assert_msg(
/// 	|e| e.amount.get() > 0,
/// 	"escrow amount must be positive",
/// )?;
/// ```
pub trait AccountValidation {
	/// Assert an immutable condition on the account data.
	fn assert<F>(&self, condition: F) -> Result<&Self, ProgramError>
	where
		F: Fn(&Self) -> bool;

	/// Assert an immutable condition with a custom log message on failure.
	fn assert_msg<F>(&self, condition: F, msg: &str) -> Result<&Self, ProgramError>
	where
		F: Fn(&Self) -> bool;

	/// Assert a condition on a mutable reference to the account data.
	fn assert_mut<F>(&mut self, condition: F) -> Result<&mut Self, ProgramError>
	where
		F: Fn(&Self) -> bool;

	/// Assert a condition on a mutable reference with a custom log message.
	fn assert_mut_msg<F>(&mut self, condition: F, msg: &str) -> Result<&mut Self, ProgramError>
	where
		F: Fn(&Self) -> bool;
}

