		let mut checked = [0u8; 8];
		0x0123_4567_89AB_CDEFu64.write_discriminator(&mut expected);
		0x0123_4567_89AB_CDEFu64
			.try_write_discriminator(&mut checked)
			.unwrap_or_else(|error| panic!("u64: {error:?}"));
