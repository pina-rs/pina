/**
 * TypeScript (commander) CLI emitter.
 *
 * Renders a Node CLI app on top of a generated `@solana/kit` client:
 * one commander subcommand per instruction, a `fetch` command per account,
 * and a shared context that owns the RPC connection, keypair, and send
 * or simulate plumbing. Global options are declared on the root command
 * and on every subcommand so they work at any position.
 */

import type {
	AccountModel,
	ArgKind,
	CliModel,
	InstructionModel,
} from "./model.ts";

export interface TypeScriptOptions {
	/** Import specifier of the generated client's `src/generated` barrel. */
	clientImportPath: string;
	/** Overrides the emitted `@solana/kit` dependency range. */
	kitVersion?: string;
}

const HEADER =
	`// This code was AUTOGENERATED by \`@pina-rs/codama-renderer-cli\`.
// Please DO NOT EDIT THIS FILE directly.
// Regenerate it from the program IDL instead.
`;

const CONTEXT = `${HEADER}
import {
	type Address,
	type Instruction,
	type KeyPairSigner,
	appendTransactionMessageInstructions,
	createKeyPairSignerFromBytes,
	createSolanaRpc,
	getBase64EncodedWireTransaction,
	isAddress,
	pipe,
	setTransactionMessageFeePayerSigner,
	setTransactionMessageLifetimeUsingBlockhash,
	getBase58Decoder,
	signAndSendTransactionMessageWithSigners,
	signTransactionMessageWithSigners,
	createTransactionMessage,
} from "@solana/kit";
import { Command } from "commander";
import { readFileSync } from "node:fs";
import { homedir } from "node:os";

const CLUSTERS: Record<string, string> = {
	"mainnet": "https://api.mainnet-beta.solana.com",
	"mainnet-beta": "https://api.mainnet-beta.solana.com",
	"devnet": "https://api.devnet.solana.com",
	"testnet": "https://api.testnet.solana.com",
	"localhost": "http://localhost:8899",
	"localnet": "http://localhost:8899",
};

export interface GlobalOptions {
	url?: string;
	keypair?: string;
	programId?: string;
	simulate?: boolean;
	json?: boolean;
}

/** Registers the shared global options on one commander command. */
export function registerGlobals(command: Command): Command {
	return command
		.option("-u, --url <url>", "RPC endpoint: mainnet, devnet, testnet, localhost, or an https URL.")
		.option("-k, --keypair <path>", "Payer keypair JSON file.")
		.option("--program-id <address>", "Override the on-chain program address.")
		.option("--simulate", "Simulate the transaction and print logs instead of sending.")
		.option("--json", "Print machine-readable JSON output.");
}

export class CliError extends Error {}

export class CliContext {
	readonly rpc: ReturnType<typeof createSolanaRpc>;
	readonly payer: KeyPairSigner;
	readonly programAddress: Address;
	readonly simulate: boolean;
	readonly json: boolean;
	private readonly cluster: string;

	private constructor(
		rpc: ReturnType<typeof createSolanaRpc>,
		payer: KeyPairSigner,
		programAddress: Address,
		simulate: boolean,
		json: boolean,
		cluster: string,
	) {
		this.rpc = rpc;
		this.payer = payer;
		this.programAddress = programAddress;
		this.simulate = simulate;
		this.json = json;
		this.cluster = cluster;
	}

	static async create(options: GlobalOptions): Promise<CliContext> {
		const url = options.url ?? process.env.SOLANA_URL ?? "devnet";
		const keypair = options.keypair ?? process.env.PINA_KEYPAIR ?? "~/.config/solana/id.json";
		const endpoint = resolveEndpoint(url);
		const rpc = createSolanaRpc(endpoint as Parameters<typeof createSolanaRpc>[0]);
		const payer = await loadKeypair(keypair);
		const programAddress = options.programId
			? (options.programId as Address)
			: (PROGRAM_ADDRESS as Address);
		return new CliContext(rpc, payer, programAddress, options.simulate ?? false, options.json ?? false, clusterOf(endpoint));
	}

	async send(instruction: Instruction): Promise<void> {
		const { value: latestBlockhash } = await this.rpc
			.getLatestBlockhash()
			.send();
		const message = pipe(
			createTransactionMessage({ version: 0 }),
			(m) => setTransactionMessageFeePayerSigner(this.payer, m),
			(m) => setTransactionMessageLifetimeUsingBlockhash(latestBlockhash, m),
			(m) => appendTransactionMessageInstructions([instruction], m),
		);

		if (this.simulate) {
			const transaction = await signTransactionMessageWithSigners(message);
			const base64 = getBase64EncodedWireTransaction(transaction);
			const simulation = await this.rpc
				.simulateTransaction(base64, {
					encoding: "base64",
					sigVerify: false,
					replaceRecentBlockhash: true,
				})
				.send();
			const result = simulation.value;
			const logs = result.logs ?? [];
			if (this.json) {
				console.log(JSON.stringify({ logs, unitsConsumed: result.unitsConsumed }));
			} else {
				for (const log of logs) {
					console.log(log);
				}
				if (result.unitsConsumed != null) {
					console.log(\`Consumed \${result.unitsConsumed} compute units\`);
				}
			}
			if (result.err != null) {
				throw new CliError(
					\`the transaction failed: \${JSON.stringify(result.err)}\\n\${logs.join("\\n")}\`,
				);
			}
			return;
		}

		const signatureBytes = await signAndSendTransactionMessageWithSigners(message);
		const signature58 = getBase58Decoder().decode(signatureBytes);
		if (this.json) {
			console.log(JSON.stringify({ signature: signature58 }));
		} else {
			console.log(\`Signature: \${signature58}\`);
			const suffix = this.cluster ? \`?cluster=\${this.cluster}\` : "";
			console.log(\`https://explorer.solana.com/tx/\${signature58}\${suffix}\`);
		}
	}
}

export function pubkey(flag: string, value: string): Address {
	if (!isAddress(value)) {
		throw new CliError(\`\${flag} must be a base58 public key\`);
	}
	return value;
}

export function smallInteger(flag: string, value: string): number {
	const parsed = Number(value);
	if (!Number.isSafeInteger(parsed)) {
		throw new CliError(\`\${flag} must be an integer\`);
	}
	return parsed;
}

export function bigInteger(flag: string, value: string): bigint {
	try {
		return BigInt(value);
	} catch {
		throw new CliError(\`\${flag} must be a 64-bit integer\`);
	}
}

export function base58Vec(flag: string, value: string): number[] {
	const fixed = base58(flag, value);
	return Array.from(fixed);
}

export function base58(flag: string, value: string): Uint8Array {
	try {
		const ALPHABET = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";
		let num = 0n;
		for (const character of value) {
			const digit = ALPHABET.indexOf(character);
			if (digit < 0) {
				throw new Error("invalid character");
			}
			num = num * 58n + BigInt(digit);
		}
		const bytes: number[] = [];
		while (num > 0n) {
			bytes.unshift(Number(num % 256n));
			num /= 256n;
		}
		let leading = 0;
		for (const character of value) {
			if (character !== "1") break;
			leading += 1;
		}
		return new Uint8Array([...new Array<number>(leading).fill(0), ...bytes]);
	} catch {
		throw new CliError(\`\${flag} must be valid base58\`);
	}
}

function resolveEndpoint(value: string): string {
	const endpoint = CLUSTERS[value] ?? value;
	const lowercase = endpoint.toLowerCase();
	const isLocal =
		lowercase.startsWith("http://localhost") ||
		lowercase.startsWith("http://127.0.0.1") ||
		lowercase.startsWith("http://[::1]");
	if (!lowercase.startsWith("https://") && !(lowercase.startsWith("http://") && isLocal)) {
		throw new CliError(
			"plaintext http:// endpoints are only allowed on localhost; use https for remote clusters",
		);
	}
	return endpoint;
}

function clusterOf(endpoint: string): string {
	if (endpoint.includes("api.mainnet-beta.solana.com")) return "";
	if (endpoint.includes("api.devnet.solana.com")) return "devnet";
	if (endpoint.includes("api.testnet.solana.com")) return "testnet";
	return "";
}

async function loadKeypair(path: string): Promise<KeyPairSigner> {
	const expanded = path.startsWith("~/") ? \`\${homedir()}/\${path.slice(2)}\` : path;
	const bytes = JSON.parse(readFileSync(expanded, "utf8")) as number[];
	if (!Array.isArray(bytes) || bytes.length !== 64) {
		throw new CliError(
			\`could not load payer keypair \\\`\${expanded}\\\`: expected a JSON array of 64 bytes\`,
		);
	}
	return await createKeyPairSignerFromBytes(new Uint8Array(bytes));
}
`;

const kebab = (value: string): string => value.replace(/_/g, "-");

function optionFlag(name: string): string {
	return `--${kebab(name)}`;
}

function docLines(docs: string[]): string[] {
	return docs.flatMap((doc) => doc.split("\n"));
}

function argValueExpression(arg: InstructionModel["args"][number]): string {
	const flag = JSON.stringify(optionFlag(arg.snake));
	switch (arg.type.kind) {
		case "number":
			return arg.type.format.startsWith("u64") ||
					arg.type.format.startsWith("i64")
				? `bigInteger(${flag}, options.${arg.camel})`
				: `smallInteger(${flag}, options.${arg.camel})`;
		case "pubkey":
			return `pubkey(${flag}, options.${arg.camel})`;
		case "fixedBytes":
			return `base58(${flag}, options.${arg.camel})`;
		case "byteVec":
			return `base58Vec(${flag}, options.${arg.camel})`;
		default:
			return `options.${arg.camel}`;
	}
}

function commandDescription(docs: string[], fallback: string): string {
	return JSON.stringify(docs.join("\n") || fallback);
}

function renderCommand(instruction: InstructionModel): string {
	const options: string[] = [];

	for (const arg of instruction.args) {
		const description = docLines(arg.docs)[0] ?? arg.camel;
		options.push(
			`\t.requiredOption("${optionFlag(arg.snake)} <${arg.camel}>", ${
				JSON.stringify(description)
			})`,
		);
	}

	for (const account of instruction.accounts) {
		if (account.resolution.resolution === "constant") {
			continue;
		}
		const required = account.resolution.resolution === "required";
		const hint = account.resolution.resolution === "pda"
			? " [default: derived]"
			: account.resolution.resolution === "payer"
			? " [default: payer]"
			: "";
		const description =
			(docLines(account.docs)[0] ?? `The \`${account.snake}\` account.`)
				.replace(/\.$/, "");
		const flag = `${optionFlag(account.snake)} <${account.camel}>`;
		options.push(
			required
				? `\t.requiredOption("${flag}", ${JSON.stringify(description)})`
				: `\t.option("${flag}", ${JSON.stringify(`${description}${hint}`)})`,
		);
	}

	const inputEntries: string[] = [];
	for (const arg of instruction.args) {
		inputEntries.push(`\t\t${arg.camel}: ${argValueExpression(arg)},`);
	}
	for (const account of instruction.accounts) {
		switch (account.resolution.resolution) {
			case "constant":
				continue;
			case "payer":
				inputEntries.push(`\t\t${account.camel}: context.payer,`);
				break;
			case "pda":
				inputEntries.push(`\t\t${account.camel}: options.${account.camel},`);
				break;
			default:
				inputEntries.push(
					`\t\t${account.camel}: pubkey(${
						JSON.stringify(optionFlag(account.snake))
					}, options.${account.camel}),`,
				);
		}
	}

	const inputObject = inputEntries.length > 0
		? `const input = {\n${inputEntries.join("\n")}\n\t};`
		: "const input = null;";

	return `${HEADER}
import { Command } from "commander";
import { get${instruction.pascal}Instruction${
		instruction.hasAsyncBuilder ? "Async" : ""
	} } from "../client";
import { CliContext, base58, base58Vec, bigInteger, pubkey, registerGlobals, smallInteger } from "../context";

export const ${instruction.camel}Command = registerGlobals(new Command("${instruction.snake}"))
	.description(${commandDescription(instruction.docs, instruction.camel)})
${options.join("\n")}
	.action(async (options) => {
		const context = await CliContext.create(options);
${inputObject}
		const instruction = ${
		instruction.hasAsyncBuilder ? "await " : ""
	}get${instruction.pascal}Instruction${
		instruction.hasAsyncBuilder ? "Async" : ""
	}(
			...${inputEntries.length > 0 ? "[input]" : "[]"},
			{ programAddress: context.programAddress },
		);
		await context.send(instruction);
	});
`;
}

function renderFetch(model: CliModel): string {
	const subcommands = model.accounts
		.map((account) => {
			const options = [
				`\t\t\t\t.option("--address <address>", "Account address; overrides PDA derivation.")`,
			];
			const seedLocals: string[] = [];
			const seedNames: string[] = [];
			for (const seed of account.seeds ?? []) {
				if (seed.constant) {
					continue;
				}
				options.push(
					`\t\t\t\t.requiredOption("${
						optionFlag(seed.snake)
					} <${seed.camel}>", ${
						JSON.stringify(`PDA seed \`${seed.snake}\`.`)
					})`,
				);
				seedLocals.push(
					`\tconst ${seed.camel} = ${
						seed.type.kind === "pubkey"
							? `pubkey(${
								JSON.stringify(optionFlag(seed.snake))
							}, options.${seed.camel} as string)`
							: `bigInteger(${
								JSON.stringify(optionFlag(seed.snake))
							}, options.${seed.camel} as string)`
					};`,
				);
				seedNames.push(seed.camel);
			}

			const derivation = (account.seeds ?? []).some((seed) => !seed.constant)
				? `${seedLocals.join("\n")}
					const address = options.address ??
						(await find${account.pdaPascal ?? account.pascal}Pda({ ${
					seedNames.join(", ")
				} }, { programAddress: context.programAddress }))[0];`
				: `\t\t\t\t\tconst address = pubkey("--address", options.address as string);`;

			return `\t\t.addCommand(
				registerGlobals(new Command("${kebab(account.snake)}"))
					.description(${commandDescription(account.docs, account.snake)})
${options.join("\n")}
					.action(async (options) => {
						const context = await CliContext.create(options);
${derivation}
						const account = await fetch${account.pascal}(context.rpc, address);
						printAccount(context.json, "${
				kebab(account.snake)
			}", address, account.data);
					}),
			)`;
		})
		.join("\n");

	const findImports = model.accounts
		.filter((account) => (account.seeds ?? []).some((seed) => !seed.constant))
		.map((account) => `\tfind${account.pdaPascal ?? account.pascal}Pda,`)
		.join("\n");
	const fetchImports = model.accounts
		.map((account) => `\tfetch${account.pascal},`)
		.join("\n");

	return `${HEADER}
import { Command } from "commander";
import {
${findImports}
${fetchImports}
} from "./client";
import { CliContext, bigInteger, pubkey, registerGlobals } from "./context";

export const fetchCommand = registerGlobals(new Command("fetch"))
	.description("Fetch and decode program accounts.")
${subcommands}
	;

function printAccount(json: boolean, name: string, address: string, data: unknown): void {
	if (json) {
		console.log(JSON.stringify({ address, ...(data as object) }, null, "\\t"));
		return;
	}
	console.log(\`\${name} \${address}\`);
	const fields = data as Record<string, unknown>;
	for (const [key, value] of Object.entries(fields)) {
		console.log(\`  \${key}: \${value}\`);
	}
}
`;
}

function renderMain(model: CliModel): string {
	const bin = `${model.programKebab}-cli`;
	const commandImports = model.instructions
		.map((instruction) =>
			`import { ${instruction.camel}Command } from "./commands/${instruction.snake}.ts";`
		)
		.join("\n");
	const fetchImport = model.accounts.length > 0
		? `import { fetchCommand } from "./fetch.ts";`
		: "";
	const registrations = [
		...model.instructions.map(
			(instruction) => `program.addCommand(${instruction.camel}Command);`,
		),
		...(model.accounts.length > 0 ? ["program.addCommand(fetchCommand);"] : []),
	].join("\n");

	return `${HEADER}
import { Command } from "commander";
${commandImports}
${fetchImport}
import { registerGlobals } from "./context.ts";

const program = registerGlobals(new Command())
	.name("${bin}")
	.version("0.1.0")
	.description(${JSON.stringify(model.about)});
${registrations}
program.parseAsync(process.argv);
`;
}

/** Render every file of the TypeScript CLI app. */
export function renderTypeScript(
	model: CliModel,
	options: TypeScriptOptions,
): Map<string, string> {
	const files = new Map<string, string>();
	const bin = `${model.programKebab}-cli`;

	files.set(
		"src/client.ts",
		`${HEADER}\nexport * from "${options.clientImportPath}";\n`,
	);
	files.set(
		"src/context.ts",
		CONTEXT.replace("PROGRAM_ADDRESS", JSON.stringify(model.programAddress)),
	);
	files.set("src/main.ts", renderMain(model));

	for (const instruction of model.instructions) {
		files.set(
			`src/commands/${instruction.snake}.ts`,
			renderCommand(instruction),
		);
	}

	if (model.accounts.length > 0) {
		files.set("src/fetch.ts", renderFetch(model));
	}

	files.set(
		"package.json",
		`${
			JSON.stringify(
				{
					name: bin,
					version: "0.1.0",
					description: model.about,
					type: "module",
					private: true,
					bin: { [bin]: "./src/main.ts" },
					scripts: { start: "tsx src/main.ts" },
					dependencies: {
						"@cliffy/command": "^2.5.0",
						"@solana/kit": options.kitVersion ?? "^6.10.0",
					},
					devDependencies: { tsx: "^4.20.0", typescript: "^5.9.0" },
				},
				null,
				"\t",
			)
		}\n`,
	);
	files.set(
		"tsconfig.json",
		`${
			JSON.stringify(
				{
					compilerOptions: {
						target: "ES2022",
						module: "NodeNext",
						moduleResolution: "nodenext",
						strict: true,
						noEmit: true,
						skipLibCheck: true,
						allowImportingTsExtensions: true,
					},
					include: ["src/**/*.ts"],
				},
				null,
				"\t",
			)
		}\n`,
	);
	files.set(
		"README.md",
		`# ${bin}

Generated command-line interface for the \`${model.programCamel}\` program (version ${model.programVersion}).

This app was generated by \`pina generate --client cli-typescript\`. Do not edit
it by hand; regenerate it instead.

## Run

\`\`\`sh
npx tsx src/main.ts --help
\`\`\`

Global flags:

- \`-u, --url <URL>\`: \`mainnet\`, \`devnet\`, \`testnet\`, \`localhost\`, or an https URL (\`SOLANA_URL\`)
- \`-k, --keypair <PATH>\`: payer keypair file (\`PINA_KEYPAIR\`, default \`~/.config/solana/id.json\`)
- \`--program-id <ADDRESS>\`: override the on-chain program address
- \`--simulate\`: simulate instead of sending
- \`--json\`: machine-readable output
`,
	);

	return files;
}
