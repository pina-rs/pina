/**
 * Dart (`args` package) CLI emitter.
 *
 * Renders a Dart CLI on top of a generated solana_kit client: one
 * `Command` per instruction with typed options, PDA derivation through the
 * client's `find<Pascal>Pda` helpers, a `fetch` command per account decoded
 * through the client's `decode<Pascal>` helpers, and a shared context that
 * owns the RPC connection, keypair, and send or simulate plumbing.
 *
 * Sources for one program live under `lib/src/<program>/**` with an
 * executable at `bin/<program>.dart`, inside a shared package whose
 * `pubspec.yaml` is scaffolded by the caller.
 */

import type { ArgKind, CliModel, InstructionModel } from "./model.ts";

export interface DartOptions {
	/** Name of the Dart package these sources belong to. */
	packageName: string;
	/** Import of the generated client package's per-program barrel. */
	clientBarrel: string;
}

const HEADER =
	`// This code was AUTOGENERATED by \`@pina-rs/codama-renderer-cli\`.
// Please DO NOT EDIT THIS FILE directly.
// Regenerate it from the program IDL instead.
`;

const CONTEXT = `${HEADER}
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:args/args.dart';
import 'package:solana_kit_address/solana_kit_address.dart';
import 'package:solana_kit_instructions/solana_kit_instructions.dart';
import 'package:solana_kit_keys/solana_kit_keys.dart';
import 'package:solana_kit_rpc/solana_kit_rpc.dart';
import 'package:solana_kit_rpc_api/solana_kit_rpc_api.dart';
import 'package:solana_kit_rpc_spec/solana_kit_rpc_spec.dart';
import 'package:solana_kit_rpc_types/solana_kit_rpc_types.dart' hide TransactionVersion;
import 'package:solana_kit_transaction_messages/solana_kit_transaction_messages.dart';
import 'package:solana_kit_transactions/solana_kit_transactions.dart';

const clusters = <String, String>{
  'mainnet': 'https://api.mainnet-beta.solana.com',
  'mainnet-beta': 'https://api.mainnet-beta.solana.com',
  'devnet': 'https://api.devnet.solana.com',
  'testnet': 'https://api.testnet.solana.com',
  'localhost': 'http://localhost:8899',
  'localnet': 'http://localhost:8899',
};

class CliError implements Exception {
  CliError(this.message);

  final String message;

  @override
  String toString() => message;
}

class CliContext {
  CliContext._({
    required this.rpc,
    required this.payer,
    required this.programAddress,
    required this.simulate,
    required this.json,
  });

  final Rpc rpc;
  final KeyPair payer;
  final Address programAddress;
  final bool simulate;
  final bool json;

  Address get payerAddress => getAddressFromPublicKey(payer.publicKey);

  Future<void> send(Iterable<Instruction> instructions) async {
    final blockhashResponse = await rpc.getLatestBlockhashValue().send();
    final blockhashValue = blockhashResponse.value;

    final message = setTransactionMessageLifetimeUsingBlockhash(
      BlockhashLifetimeConstraint(
        blockhash: blockhashValue.blockhash.value,
        lastValidBlockHeight: blockhashValue.lastValidBlockHeight,
      ),
      TransactionMessage(
        version: TransactionVersion.legacy,
        instructions: instructions.toList(),
        feePayer: payerAddress,
      ),
    );
    final compiled = compileTransactionMessage(message);
    final messageBytes = getCompiledTransactionMessageEncoder().encode(compiled);
    final unsigned = Transaction(
      messageBytes: messageBytes,
      signatures: {payerAddress: null},
    );
    final signed = await signTransaction([payer], unsigned);
    final wire = base64Encode(getTransactionEncoder().encode(signed));

    if (simulate) {
      final simulation = await rpc
          .request<Object?>('simulateTransaction', [
            wire,
            const SimulateTransactionConfig(
              encoding: WireTransactionEncoding.base64,
              sigVerify: false,
              replaceRecentBlockhash: true,
            ),
          ])
          .send();
      final result = ((simulation as Map<String, Object?>)['result']
              as Map<String, Object?>)['value']!
          as Map<String, Object?>;
      final logs = (result['logs'] as List<Object?>? ?? <Object?>[])
          .map((log) => log.toString())
          .toList();
      if (json) {
        stdout.writeln(
          jsonEncode({'logs': logs, 'unitsConsumed': result['unitsConsumed']}),
        );
      } else {
        for (final log in logs) {
          stdout.writeln(log);
        }
        final units = result['unitsConsumed'];
        if (units != null) {
          stdout.writeln('Consumed \${units.toString()} compute units');
        }
      }
      if (result['err'] != null) {
        throw CliError('the transaction failed: \${result['err'].toString()}');
      }
      return;
    }

    final signature = await rpc.sendTransaction(wire).send();
    if (json) {
      stdout.writeln(jsonEncode({'signature': signature}));
    } else {
      stdout.writeln('Signature: \${signature.toString()}');
      stdout.writeln('https://explorer.solana.com/tx/\${signature.toString()}');
    }
  }

  Future<Uint8List> fetchAccount(Address address) async {
    final response = await rpc
        .getAccountInfo(
          address,
          GetAccountInfoConfig(encoding: AccountEncoding.base64),
        )
        .send();
    final value = (response['result'] as Map<String, Object?>)['value']
        as Map<String, Object?>?;
    if (value == null) {
      throw CliError('account \${address.toString()} was not found');
    }
    final owner = value['owner']! as String;
    if (owner != programAddress.toString()) {
      throw CliError(
        'account \${address.toString()} belongs to \${owner}, not the configured program',
      );
    }
    final data = value['data']! as List<Object?>;
    return base64Decode(data[0]! as String);
  }
}

Address pubkey(String flag, String value) {
  try {
    return Address(value);
  } on FormatException {
    throw CliError('\${flag} must be a base58 public key');
  }
}

int integer(String flag, String value) {
  final parsed = int.tryParse(value);
  if (parsed == null) {
    throw CliError('\${flag} must be an integer');
  }
  return parsed;
}

BigInt bigInteger(String flag, String value) {
  try {
    return BigInt.parse(value);
  } on FormatException {
    throw CliError('\${flag} must be a 64-bit integer');
  }
}

Uint8List base58Bytes(String flag, String value) {
  const alphabet = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';
  var num = BigInt.zero;
  for (final character in value.split('')) {
    final digit = alphabet.indexOf(character);
    if (digit < 0) {
      throw CliError('\${flag} must be valid base58');
    }
    num = num * BigInt.from(58) + BigInt.from(digit);
  }
  final bytes = <int>[];
  while (num > BigInt.zero) {
    bytes.insert(0, (num % BigInt.from(256)).toInt());
    num ~/= BigInt.from(256);
  }
  final leading = value.split('').takeWhile((c) => c == '1').length;
  return Uint8List.fromList([...List<int>.filled(leading, 0), ...bytes]);
}

String resolveEndpoint(String value) {
  final endpoint = clusters[value] ?? value;
  final lowercase = endpoint.toLowerCase();
  final isLocal = lowercase.startsWith('http://localhost') ||
      lowercase.startsWith('http://127.0.0.1') ||
      lowercase.startsWith('http://[::1]');
  if (!lowercase.startsWith('https://') &&
      !(lowercase.startsWith('http://') && isLocal)) {
    throw CliError(
      'plaintext http:// endpoints are only allowed on localhost; '
      'use https for remote clusters',
    );
  }
  return endpoint;
}

KeyPair loadKeypair(String path) {
  final expanded = path.startsWith('~/')
      ? '\${Platform.environment['HOME']}/\${path.substring(2)}'
      : path;
  final bytes = (jsonDecode(File(expanded).readAsStringSync()) as List<Object?>)
      .map((byte) => (byte! as num).toInt())
      .toList();
  if (bytes.length != 64) {
    throw CliError(
      'could not load payer keypair: expected a JSON array of 64 bytes',
    );
  }
  return KeyPair(
    privateKey: Uint8List.fromList(bytes.sublist(0, 32)),
    publicKey: Uint8List.fromList(bytes.sublist(32)),
  );
}

Future<CliContext> createContext(ArgResults globals) {
  return Future.sync(() {
    return CliContext._(
      rpc: createSolanaRpc(url: resolveEndpoint(globals['url']! as String)),
      payer: loadKeypair(globals['keypair']! as String),
      programAddress: (globals['program-id'] as String?) != null
          ? pubkey('--program-id', globals['program-id']! as String)
          : Address(PROGRAM_ADDRESS),
      simulate: globals['simulate'] as bool? ?? false,
      json: globals['json'] as bool? ?? false,
    );
  });
}

void printFields(
  bool json,
  String name,
  Address address,
  Map<String, Object?> fields,
) {
  if (json) {
    stdout.writeln(jsonEncode({'address': address.toString(), ...fields}));
    return;
  }
  stdout.writeln('\${name} \${address.toString()}');
  for (final entry in fields.entries) {
    stdout.writeln('  \${entry.key}: \${entry.value}');
  }
}
`;

const kebab = (value: string): string => value.replace(/_/g, "-");

function argExpression(arg: { snake: string; type: ArgKind }): string {
	switch (arg.type.kind) {
		case "number":
			return arg.type.format === "u64" || arg.type.format === "i64"
				? `bigInteger('--${
					kebab(arg.snake)
				}', results['${arg.snake}']! as String)`
				: `integer('--${
					kebab(arg.snake)
				}', results['${arg.snake}']! as String)`;
		case "pubkey":
			return `pubkey('--${
				kebab(arg.snake)
			}', results['${arg.snake}']! as String)`;
		case "fixedBytes":
		case "byteVec":
			return `base58Bytes('--${
				kebab(arg.snake)
			}', results['${arg.snake}']! as String)`;
		default:
			return `results['${arg.snake}']! as String`;
	}
}

function seedName(
	seed: { seed: string; account?: string; arg?: string },
): string {
	const name = seed.account ?? seed.arg ?? "";
	return name.replace(
		/_([a-z0-9])/g,
		(_, letter: string) => letter.toUpperCase(),
	);
}

function accountLocals(instruction: InstructionModel): string {
	const locals: string[] = [];
	for (const account of instruction.accounts) {
		const override = `(results['${account.snake}'] as String?) != null
        ? pubkey('--${
			kebab(account.snake)
		}', results['${account.snake}']! as String)
        : `;
		switch (account.resolution.resolution) {
			case "constant":
				continue;
			case "payer":
				locals.push(
					`    final ${account.camel} = ${override}context.payerAddress;`,
				);
				break;
			case "pda": {
				const seedList = (account.resolution.seeds ?? [])
					.map((seed) => `${seedName(seed)}: ${seedName(seed)}`)
					.join(", ");
				const seedsArg = seedList
					? `          seeds: ${account.resolution.pascal}Seeds(${seedList}),
`
					: "";
				locals.push(
					`    final ${account.camel} = ${override}(await find${account.resolution.pascal}Pda(
${seedsArg}          programAddress: context.programAddress,
        )).$1;`,
				);
				break;
			}
			default:
				locals.push(
					`    final ${account.camel} = pubkey('--${
						kebab(account.snake)
					}', results['${account.snake}']! as String);`,
				);
		}
	}
	return locals.join("\n");
}

function factoryParams(instruction: InstructionModel): string {
	const params = ["      programAddress: context.programAddress,"];
	for (const account of instruction.accounts) {
		if (account.resolution.resolution === "constant") {
			params.push(
				`      ${account.camel}: Address('${account.resolution.address}'),`,
			);
		} else {
			params.push(`      ${account.camel}: ${account.camel},`);
		}
	}
	for (const arg of instruction.args) {
		params.push(`      ${arg.camel}: ${arg.camel}Value,`);
	}
	return params.join("\n");
}

function usesResults(instruction: InstructionModel): boolean {
	return (
		instruction.accounts.some(
			(account) => account.resolution.resolution !== "constant",
		) || instruction.args.length > 0
	);
}

function optionAdders(instruction: InstructionModel): string {
	const adders: string[] = [];
	for (const arg of instruction.args) {
		adders.push(
			`      ..addOption('${arg.snake}', mandatory: true, help: ${
				JSON.stringify(arg.docs[0]?.split("\n")[0] ?? arg.camel)
			})`,
		);
	}
	for (const account of instruction.accounts) {
		if (account.resolution.resolution === "constant") {
			continue;
		}
		const mandatory = account.resolution.resolution === "required";
		const hint = account.resolution.resolution === "pda"
			? " [default: derived]"
			: account.resolution.resolution === "payer"
			? " [default: payer]"
			: "";
		const help =
			(account.docs[0]?.split("\n")[0] ?? `The ${account.snake} account.`)
				.replace(/\.$/, "");
		adders.push(
			`      ..addOption('${account.snake}', mandatory: ${
				mandatory ? "true" : "false"
			}, help: ${JSON.stringify(`${help}${hint}`)})`,
		);
	}
	return adders.join("\n");
}

function renderInstructionCommand(
	instruction: InstructionModel,
	clientBarrel: string,
): string {
	return `${HEADER}
import 'package:args/command_runner.dart';

import 'package:solana_kit_address/solana_kit_address.dart';

import '../context.dart';
import '${clientBarrel}';

final class ${instruction.pascal}Command extends Command<void> {
  ${instruction.pascal}Command() {
    argParser
${optionAdders(instruction)};
  }

  @override
  String get name => '${instruction.snake}';

  @override
  String get description => ${
		JSON.stringify(
			instruction.docs.join(" ").split("\n")[0] || instruction.snake,
		)
	};

  @override
  Future<void> run() async {
${usesResults(instruction) ? "    final results = argResults!;" : ""}
    final context = await createContext(globalResults!);
${accountLocals(instruction)}
${
		instruction.args.map((arg) =>
			`    final ${arg.camel}Value = ${argExpression(arg)};`
		).join("\n")
	}
    final instruction = get${instruction.pascal}Instruction(
${factoryParams(instruction)}
    );
    await context.send([instruction]);
  }
}
`;
}

function renderFetchCommand(model: CliModel, clientBarrel: string): string {
	const commands = model.accounts
		.map((account) => {
			const variableSeeds = (account.seeds ?? []).filter((seed) =>
				!seed.constant
			);
			const adders = [
				"      ..addOption('address', help: 'Account address; overrides PDA derivation.')",
				...variableSeeds.map((seed) =>
					`      ..addOption('${seed.snake}', mandatory: true, help: ${
						JSON.stringify(`PDA seed \`${seed.snake}\`.`)
					})`
				),
			].join("\n");

			const seedValues = variableSeeds
				.map((seed) =>
					seed.type.kind === "pubkey"
						? `    final ${seed.camel}Value = pubkey('--${
							kebab(seed.snake)
						}', results['${seed.snake}']! as String);`
						: seed.type.kind === "number" && seed.type.format === "u64"
						? `    final ${seed.camel}Value = bigInteger('--${
							kebab(seed.snake)
						}', results['${seed.snake}']! as String);`
						: `    final ${seed.camel}Value = integer('--${
							kebab(seed.snake)
						}', results['${seed.snake}']! as String);`
				)
				.join("\n");

			const derivation = variableSeeds.length > 0
				? `${seedValues}
    final address = (results['address'] as String?) != null
        ? pubkey('--address', results['address']! as String)
        : (await find${account.pdaPascal ?? account.pascal}Pda(
${
					variableSeeds.length > 0
						? `            seeds: ${account.pdaPascal ?? account.pascal}Seeds(
${
							variableSeeds.map((seed) =>
								`              ${seed.camel}: ${seed.camel}Value`
							).join(",\n")
						},
            ),
`
						: ""
				}            programAddress: context.programAddress,
          )).$1;`
				: `    final address = pubkey('--address', results['address']! as String);`;

			const fieldEntries = account.fields
				.map((field) =>
					`        '${field.snake}': account.data.${field.camel},`
				)
				.join("\n");

			return `final class Fetch${account.pascal}Command extends Command<void> {
  Fetch${account.pascal}Command() {
    argParser
${adders};
  }

  @override
  String get name => '${kebab(account.snake)}';

  @override
  String get description => ${
				JSON.stringify(account.docs[0]?.split("\n")[0] ?? account.snake)
			};

  @override
  Future<void> run() async {
    final results = argResults!;
    final context = await createContext(globalResults!);
${derivation}
    final data = await context.fetchAccount(address);
    final encoded = Account<Uint8List>(
      address: address,
      data: data,
      executable: false,
      lamports: Lamports(BigInt.zero),
      programAddress: context.programAddress,
      space: BigInt.from(data.length),
    );
    final account = decode${account.pascal}(encoded);
    printFields(
      context.json,
      '${kebab(account.snake)}',
      address,
      <String, Object?>{
${fieldEntries}
      },
    );
  }
}
`;
		})
		.join("\n");

	return `${HEADER}
import 'dart:typed_data';

import 'package:args/command_runner.dart';
import 'package:solana_kit_accounts/solana_kit_accounts.dart';
import 'package:solana_kit_rpc_types/solana_kit_rpc_types.dart' hide TransactionVersion;

import '../context.dart';
import '${clientBarrel}';

${commands}
final class FetchCommand extends Command<void> {
  @override
  String get name => 'fetch';

  @override
  String get description => 'Fetch and decode program accounts.';
}
`;
}

function renderMain(model: CliModel): string {
	const registrations = [
		...model.instructions.map(
			(instruction) => `    ..addCommand(${instruction.pascal}Command())`,
		),
		...(model.accounts.length > 0 ? ["    ..addCommand(FetchCommand())"] : []),
	].join("\n");

	return `${HEADER}
import 'package:args/command_runner.dart';

import 'commands/commands.dart';

CommandRunner<void> buildRunner() {
  return CommandRunner<void>(
    '${model.programKebab}-cli',
    ${JSON.stringify(model.about)},
  )
    ..argParser.addOption(
        'url',
        abbr: 'u',
        defaultsTo: 'devnet',
        help: 'RPC endpoint: mainnet, devnet, testnet, localhost, or an https URL.',
      )
    ..argParser.addOption(
        'keypair',
        abbr: 'k',
        defaultsTo: '~/.config/solana/id.json',
        help: 'Payer keypair JSON file.',
      )
    ..argParser.addOption(
        'program-id',
        help: 'Override the on-chain program address.',
      )
    ..argParser.addFlag(
        'simulate',
        help: 'Simulate the transaction and print logs instead of sending.',
      )
    ..argParser.addFlag(
        'json',
        negatable: false,
        help: 'Print machine-readable JSON output.',
      )
${registrations};
}
`;
}

/** Render one program's Dart CLI sources within a shared package layout. */
export function renderDart(
	model: CliModel,
	options: DartOptions,
): Map<string, string> {
	const files = new Map<string, string>();
	const stem = model.programSnake;
	const clientBarrel = options.clientBarrel;

	files.set(
		`lib/src/${stem}/context.dart`,
		CONTEXT.replace("PROGRAM_ADDRESS", JSON.stringify(model.programAddress)),
	);

	for (const instruction of model.instructions) {
		files.set(
			`lib/src/${stem}/commands/${instruction.snake}.dart`,
			renderInstructionCommand(instruction, clientBarrel),
		);
	}
	if (model.accounts.length > 0) {
		files.set(
			`lib/src/${stem}/commands/fetch.dart`,
			renderFetchCommand(model, clientBarrel),
		);
	}

	const barrelExports = [
		...model.instructions.map((instruction) =>
			`export '${instruction.snake}.dart';`
		),
		...(model.accounts.length > 0 ? ["export 'fetch.dart';"] : []),
	].join("\n");
	files.set(
		`lib/src/${stem}/commands/commands.dart`,
		`${HEADER}\n${barrelExports}\n`,
	);

	files.set(`lib/src/${stem}/main.dart`, renderMain(model));
	files.set(
		`bin/${stem}.dart`,
		`${HEADER}
import 'package:args/command_runner.dart';

import 'package:${options.packageName}/src/${stem}/main.dart';

Future<void> main(List<String> arguments) async {
  await buildRunner().run(arguments);
}
`,
	);

	return files;
}
